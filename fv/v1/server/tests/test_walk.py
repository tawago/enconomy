def check_record_shape(rec, op, bad):
    """A final record holds what spec section 3.1 lists. The zk block is out of scope and isn't opened."""
    if set(rec) != RECORD_KEYS:
        bad("M5", f"record has other keys: {sorted(set(rec) ^ RECORD_KEYS)}")
    for r, v in rec.get("devices", {}).items():
        if set(v) != RECORD_DEVICE_KEYS:
            bad("M5", f"record device {r} has other keys: {sorted(set(v) ^ RECORD_DEVICE_KEYS)}")
    for r, v in rec.get("transcripts", {}).items():
        if set(v) != {"transcript_b64", "sig_b64", "sha256"}:
            bad("M5", f"record transcript {r} has other keys: {sorted(v)}")
    for r, v in rec.get("commits", {}).items():
        if set(v) != {"commit_b64", "sig_b64"}:
            bad("M5", f"record commit {r} has other keys: {sorted(v)}")


def iso_ms(ms):
    """Written here with whole numbers, not read from the server."""
    return (datetime(1970, 1, 1, tzinfo=timezone.utc) + timedelta(milliseconds=ms)).isoformat(timespec="milliseconds")


def want_record(ctx, d):
    """The whole final record but zk, built from the stored document and the phones' device rows."""
    row = d["attempts"][-1]
    dev = {"A": d["host_device_id"], "B": d["guest_device_id"]}
    reason = d["error"]
    devices, transcripts, commits = {}, {}, {}
    for r in ROLES:
        o, p = ctx.phones[ctx.names[dev[r]]].row, d["per_role"][r]
        devices[r] = {"device_id": o["device_id"], "pubkey": o["pubkey"], "display_name": o["display_name"], "model": o["model"], "attested": o["attested"],
                      "security_level": o["security_level"], "sample_rate": p.get("sample_rate"), "half": p.get("half"), "popt": p.get("popt", 1), "cal_us": p.get("cal_us", 0)}
        if "transcript_b64" in p:
            transcripts[r] = {"transcript_b64": p["transcript_b64"], "sig_b64": p["sig_b64"], "sha256": hashlib.sha256(base64.b64decode(p["transcript_b64"])).hexdigest()}
        if "commit_b64" in p:
            commits[r] = {"commit_b64": p["commit_b64"], "sig_b64": p["commit_sig_b64"]}
    rows = []
    for a in d["attempts"]:
        x = {k: a.get(k) for k in ("attempt", "outcome", "reason", "by")}
        if a.get("outcome") == "verdict":
            x.update(verdict=a["verdict"], flight_cm=a["flight_cm"])
        rows.append(x)
    return {"proto": "pop-v1", "session_id": d["session_id"], "session_nonce": d["nonce_hex"], "context": None, "not_before": d["created_ms"] // 1000,
            "policy": {"human": "none"}, "human": None, "pair_tag": None, "attempt": d["attempt"], "verdict": row["verdict"], "reason": reason,
            "user_text": V.USER_TEXT.get(reason) if reason else None, "flight_cm": row["flight_cm"], "t0_ms": d["t0_ms"], "created_at": iso_ms(d["created_ms"]),
            "finished_at": iso_ms(d["finished_ms"]), "devices": devices, "transcripts": transcripts, "commits": commits, "attempts": rows}


def check_fixed(ctx, d, bad):
    """M1, the core fields the abstract state leaves out, and the names of what's stored."""
    for k in FIXED_KEYS:
        if d.get(k) != ctx.fixed[k]:
            bad("M1", f"{k} was rewritten")
    if set(d) - DOC_KEYS:
        bad("M1", f"the document has other fields: {sorted(set(d) - DOC_KEYS)}")
    prs = [d["per_role"]] + [a["per_role"] for a in d["attempts"] if "per_role" in a]
    for pr in prs:
        for r in ROLES:
            if set(pr[r]) - PER_ROLE_KEYS:
                bad("M1", f"per_role has other fields: {sorted(set(pr[r]) - PER_ROLE_KEYS)}")
    for a in d["attempts"]:
        if set(a) - ROW_KEYS:
            bad("M1", f"an attempts row has other fields: {sorted(set(a) - ROW_KEYS)}")
    lf = d.get("last_failure")
    if lf is not None and lf.get("text") != V.USER_TEXT.get(lf["reason"]):
        bad("M1", "last_failure text is not the fixed text for its reason")


def check_exact(op, body, want, bad):
    """M6: this response has exactly these keys. Values are checked next to it, or here when want holds them."""
    if not isinstance(body, dict):
        bad("M6", f"{op['op']} answered with something that isn't an object")
        return
    extra, gone = set(body) - set(want), set(want) - set(body)
    if extra or gone:
        bad("M6", f"{op['op']} response has other keys. new {sorted(extra)}, gone {sorted(gone)}")


def scan_response(ctx, op, status, text, body, d, info, bad):
    """M5 and M6, on every response body. Headers aren't read."""
    low = text.lower()
    for name, s in ctx.secret_forms():
        if s.lower() in low:
            bad("M5", f"{name} in a response to {op['op']}")
    if any(s.lower() in low for s in ctx.token_forms()):
        bad("M5", f"join token in a response to {op['op']}")
    role = info.get("role")
    live = d["state"] in LIVE
    keys = []
    find_keys(body, keys)
    names = {k for k, _ in keys}
    if live:
        if body.get("result") is not None if isinstance(body, dict) else False:
            bad("M6", "result shown while live")
        hit = names & LEAK_KEYS
        if hit:
            bad("M6", f"{sorted(hit)} in a response to {op['op']} while live")
    for r in ROLES:   # the partner's stored strings, while live, in plain sight
        p = d["per_role"][r]
        if live and r != role:
            for k in ("transcript_b64", "sig_b64"):
                if k in p and p[k] in text:
                    bad("M6", f"partner {k} in a response to {op['op']} while live")
    # Each kind of response is closed: known keys and known values, so a leak can't hide under a new name.
    if status >= 400:
        check_error(ctx, op, body, d, role, bad)
    elif status == 200 and op["op"] in VIEW_OPS:
        want = want_view(ctx, d, info["view_role"])
        check_exact(op, body, want, bad)
        if isinstance(body, dict):
            changed = diff(body, want)
            if changed:
                bad("M6", f"view holds other values: {str(changed)[:400]}")
    elif status == 200 and op["op"] == "transcript":
        check_exact(op, body, {"accepted": 1, "state": 1, "attempt": 1}, bad)
    elif status == 200 and op["op"] == "result":
        check_record_shape(body, op, bad)
    lf = body.get("last_failure") if isinstance(body, dict) else None
    if lf is not None and (set(lf) != {"attempt", "reason", "by", "text"} or lf["text"] != V.USER_TEXT.get(lf["reason"])):
        bad("M6", f"last_failure shows more than it should: {lf}")
    # Long strings can only be sound. Anything long must be in one of the allowed places, and equal the expected value.
    pcm_keys = {"play", "own_bed", "own_code", "partner_bed", "partner_code"}
    sounds = {k: v for k, v in keys if k in pcm_keys}
    if op["op"] == "arm" and status == 200:
        extra = set(sounds) - {"play", "own_bed", "own_code"}
        if extra:
            bad("M5", f"arm response holds {sorted(extra)}")
    elif op["op"] == "commit" and status == 200:
        extra = set(sounds) - {"partner_bed", "partner_code"}
        if extra:
            bad("M5", f"commit response holds {sorted(extra)}")
    elif sounds:
        bad("M5", f"{sorted(sounds)} in a response to {op['op']}, status {status}")
    if role is None or status != 200 or op["op"] not in ("arm", "commit"):
        for k, v in keys:
            if isinstance(v, str) and len(v) > 2000 and not (op["op"] == "result" or k in ("invite_qr",)):
                bad("M5", f"a long string under {k!r} in a response to {op['op']}, status {status}")
        return
    k = d["attempt"]
    other = OTHER[role]
    if d["t0_ms"] is None and op["op"] == "commit":
        bad("M5", "commit answered 200 with no t0")
        return
    mine = d["per_role"][role]
    sr = mine.get("sample_rate")
    if sr is None:
        bad("M5", f"{op['op']} answered 200 while not armed")
        return
    v2 = mine.get("popt") == 2
    rates = {sr}
    orate = d["per_role"][other].get("sample_rate")
    if orate:
        rates.add(orate)
    # The partner's sounds, for this attempt and the other one, at both rates. The partner's code is on this list whatever
    # popt either phone armed: a v1 phone must not get a code either.
    forbidden = []
    for at in (k, 1 - k):
        for rate in rates:
            forbidden += [("partner bed", ctx.bed(other, at, rate)["pcm_b64"]), ("partner play", ctx.play(other, at, rate)["pcm_b64"])]
            pc = ctx.code(other, at, rate)
            forbidden += [("partner code", pc["cI_b64"]), ("partner code", pc["cQ_b64"])]
            if at != k:
                oc = ctx.code(role, at, rate)
                forbidden += [("own bed of the other attempt", ctx.bed(role, at, rate)["pcm_b64"]),
                              ("own code of the other attempt", oc["cI_b64"]), ("own code of the other attempt", oc["cQ_b64"])]
    if op["op"] == "arm":
        for name, s in forbidden:
            if s in text:
                bad("M5", f"{name} in the arm response")
        want = {"attempt": k, "sample_rate": sr, "play": ctx.play(role, k, sr), "own_bed": ctx.bed(role, k, sr)}
        if v2:
            want.update(popt=2, own_code=ctx.code(role, k, sr), delta=popt2.delta(sr))
        check_exact(op, body, want, bad)
        if body["play"] != want["play"]:
            bad("M5", "arm: play is not this phone's own")
        if body["own_bed"] != want["own_bed"]:
            bad("M5", "arm: own_bed is not this phone's own")
        if v2 and body.get("own_code") != want["own_code"]:
            bad("M5", "arm: own_code is not this phone's own")
        for f in ("attempt", "sample_rate", "popt", "delta"):
            if f in want and body.get(f) != want[f]:
                bad("M6", f"arm: {f} is {body.get(f)!r}, should be {want[f]!r}")
    else:
        allowed = {ctx.bed(other, k, sr)["pcm_b64"]}
        want = {"partner_bed": ctx.bed(other, k, sr)}
        if v2:
            pc = ctx.code(other, k, sr)
            allowed |= {pc["cI_b64"], pc["cQ_b64"]}
            want.update(partner_code=pc, code_commit=mine.get("code_commit"), code_attest=mine.get("code_attest"))
        for name, s in forbidden:
            if s in text and s not in allowed:
                bad("M5", f"{name} in the commit response")
        check_exact(op, body, want, bad)
        if body.get("partner_bed") != want["partner_bed"]:
            bad("M5", "commit: partner_bed is not the partner's, for this attempt and this phone's rate")
        if v2 and body.get("partner_code") != want["partner_code"]:
            bad("M5", "commit: partner_code wrong")
        if v2 and (body.get("code_commit") != want["code_commit"] or body.get("code_attest") != want["code_attest"]):
            bad("M6", "commit: code_commit or code_attest is not this phone's own")
        # the gate
        if d["state"] != "started":
            bad("M5", f"partner code with state {d['state']}")
        if not d["committed"][role]:
            bad("M5", "partner code with no stored commit")
        elif mine["committed_ms"] < d["t0_ms"] + GATE_MS:
            bad("M5", f"partner code from a commit at t0 + {mine['committed_ms'] - d['t0_ms']}")


def check_v7(ctx, d, bad, cov):
    """The mapping table in spec V7, on the record the session really ended with."""
    rec, row = d["result"], d["attempts"][-1]
    both = set(rec["transcripts"]) == {"A", "B"} and set(rec["commits"]) == {"A", "B"}
    try:
        out = V.verify_record(rec)
    except V.Reject:
        if both:
            bad("V7", "a record with both transcripts raised")
        cov["V7:raises"] += 1
        return
    if not both:
        bad("V7", "a record with a transcript missing did not raise")
        return
    if row["outcome"] == "verdict":
        if (out["verdict"], out["reason"], out["flight_cm"], out["by"]) != (rec["verdict"], rec["reason"], rec["flight_cm"], None):
            bad("V7", f"replay {out} against record {rec['verdict']} {rec['reason']} {rec['flight_cm']}")
        cov[f"V7:{rec['verdict']}"] += 1
    elif row["outcome"] == "failed" and row["reason"] == "impossible_flight":
        if out["verdict"] is not None or out["reason"] != row["reason"] or out["flight_cm"] is None or out["by"] is not None or rec["verdict"] != "NOT_NEAR" or rec["flight_cm"] is not None:
            bad("V7", f"impossible row: {out}")
        cov["V7:impossible"] += 1
    elif row["outcome"] == "failed" and row["reason"] == "self_timestamp_mismatch":
        if out["verdict"] is not None or out["reason"] != row["reason"] or out["flight_cm"] is not None or out["by"] != row["by"] or rec["verdict"] != "NOT_NEAR":
            bad("V7", f"self row: {out}")
        cov["V7:self"] += 1
    else:
        bad("V7", f"both transcripts in a {row['outcome']} {row['reason']} record")


def check_v5(ctx, d, bad, cov):
    """Swapped pairs, on a real signed pair: the first three rows of spec V5."""
    rec = d["result"]
    if set(rec["transcripts"]) != {"A", "B"}:
        return
    ta = decode_transcript(base64.b64decode(rec["transcripts"]["A"]["transcript_b64"]))
    tb = decode_transcript(base64.b64decode(rec["transcripts"]["B"]["transcript_b64"]))

    def code(f):
        try:
            f()
        except V.Reject as e:
            return e.reason
        return None

    if code(lambda: V.combine(tb, ta, {})) != "transcript_mismatch":
        bad("V5", "combine(tb, ta) was not transcript_mismatch")
    r2 = json.loads(json.dumps(rec))
    r2["transcripts"]["A"], r2["transcripts"]["B"] = r2["transcripts"]["B"], r2["transcripts"]["A"]
    if code(lambda: V.verify_record(r2)) != "signature_invalid":
        bad("V5", "swapped transcripts in a record were not signature_invalid")
    r3 = json.loads(json.dumps(r2))
    r3["commits"]["A"], r3["commits"]["B"] = r3["commits"]["B"], r3["commits"]["A"]
    r3["devices"]["A"]["pubkey"], r3["devices"]["B"]["pubkey"] = r3["devices"]["B"]["pubkey"], r3["devices"]["A"]["pubkey"]
    if code(lambda: V.verify_record(r3)) != "transcript_mismatch":
        bad("V5", "transcripts, commits and keys all swapped were not transcript_mismatch")
    cov["V5:record"] += 1


def check_numbers_of_step(ctx, op, info, bad, cov):
    """V2, V3 and V4 on the very numbers this session's two transcripts carried."""
    r = info["role"]
    mine = op["eff"]["fields"]
    pre = ctx.model["per_role"]
    theirs = pre[OTHER[r]]
    me_p = {"half": mine["half"], "sr": mine["sr"], "delta": mine["delta"], "popt": pre[r]["popt"], "cal": pre[r]["cal"]}
    a = me_p if r == "A" else theirs
    b = me_p if r == "B" else theirs
    f = i_flight(a["half"], a["sr"], b["half"], b["sr"])
    want = (None, "impossible_flight") if f <= -20 else (("NOT_NEAR", "too_far") if f >= 60 else ("NEAR", None))
    if V.decide(f) != want:
        bad("V2", f"decide({f}) = {V.decide(f)}, the rule says {want}")
    n, s = a["half"] * b["sr"] - b["half"] * a["sr"], a["sr"] * b["sr"]
    real_f = V.flight_exact(a["half"], a["sr"], b["half"], b["sr"])
    if (Fraction(-20) < real_f < 60) != (-40 * s < 34300 * n < 120 * s):
        bad("V3", f"flight {real_f} and the integer form disagree")
    for p in (a, b):
        cal = 0 if p["popt"] == 2 else p["cal"]
        if V.self_os_ok(p["delta"], p["sr"], cal) != i_self_ok(p["delta"], p["sr"], cal):
            bad("V4", f"self check at delta {p['delta']}, rate {p['sr']}, cal {cal}")
    cov["V2-V4:on_session_numbers"] += 1


def check_view(ctx, body, m, role, op, bad):
    """A view must say what the model says."""
    base = ctx.base
    want = {"state": m["state"], "attempt": m["attempt"], "seq": m["seq"], "confirmed": m["confirmed"], "armed": m["armed"], "committed": m["committed"],
            "submitted": m["submitted"], "error": m["error"], "role": role, "t0_ms": None if m["t0"] is None else m["t0"] + base}
    for k, v in want.items():
        if body.get(k) != v:
            bad("TABLE", f"view {k} = {body.get(k)!r}, model says {v!r}")
    both = all(m["confirmed"].values())
    if body.get("nonce") != (ctx.doc_nonce_hex if both else None):
        bad("TABLE", "view nonce shown at the wrong time")
    if (body.get("result") is None) != (m["result"] is None):
        bad("TABLE", "view result and model disagree")
    if body.get("context") is not None or body.get("policy") != {"human": "none"}:
        bad("TABLE", "this walk only makes context=None, human=none sessions")


def one_step(ctx, op, cov, trace):
    """Run one op and check everything. Raises WalkFail if anything breaks."""
    now = ctx.rel()
    before_doc = ctx.doc
    before_m = ctx.model
    props = []

    def bad(p, msg):
        props.append((p, msg))

    op = dict(op)
    if op.get("auth") == "replay":   # only when minimizing can these fail to hold
        last = ctx.last_auth.get(op["actor"])
        if last is None or now >= last["first_rel"] + FORGET_MS:
            return False
    if op["op"] == "commit":
        out = realize_commit(ctx, op)
        if out is None:
            return False
        op["_body"], op["eff"] = out
    elif op["op"] == "transcript":
        out = realize_transcript(ctx, op)
        if out is None:
            return False
        op["_body"], op["eff"] = out
    pred, want_status, want_code, info = m_step(before_m, op, now, ctx.cal, ctx.last_auth)
    r, auth_rec = send(ctx, op)
    status, text = r.status_code, r.text
    try:
        body = r.json()
    except ValueError:
        body = None
    if status >= 500:
        bad("TABLE", f"status {status} on {op['op']}: {text[:300]}")
    if info["auth_ok"] and op.get("auth", "ok") != "replay":
        ctx.last_auth[op["actor"]] = auth_rec
    d = ctx.env.store.get_session(ctx.sid)
    ctx.doc = d
    code = body.get("error") if isinstance(body, dict) and status >= 400 else None
    after = abstract(ctx, d)
    if status != want_status or code != want_code:
        bad("TABLE", f"{op['op']} got {status} {code}, table says {want_status} {want_code}")
    # M1 and M14
    check_fixed(ctx, d, bad)
    if without_seq(after) != without_seq(pred):
        bad("M1", f"core fields differ from the table. real {json.dumps(diff(after, pred))}")
        if info.get("expired") is None and info.get("after_load") is before_m and want_status != 200:
            bad("M14", "an error changed the document")
    if after and pred and after["seq"] != pred["seq"]:
        bad("M1", f"seq {after['seq']}, table says {pred['seq']}")
    if pred == before_m and d != before_doc:
        bad("M14", "the document changed in a step the table says changes nothing")
    if status >= 400 and not info.get("rejected") and info.get("expired") is None and d != before_doc:
        bad("M14", f"error {status} {code} changed the document")
    # M7, M8
    if d["attempt"] not in (0, 1):
        bad("M7", f"attempt {d['attempt']}")
    if d["attempt"] < before_doc["attempt"]:
        bad("M7", "attempt went down")
    if len([a for a in d["attempts"] if a["outcome"] in ("failed", "verdict", "rejected")]) > 2:
        bad("M7", "more than two ended attempts")
    if d["attempt"] > before_doc["attempt"]:
        # One request can do two rows: E3 retries in the load, then the handler runs on attempt 1 (spec section 3.4).
        # So the sender's role may hold what this same request just wrote for attempt 1: an arm, or a fail. Nothing else may be there.
        fresh_keys = {"sample_rate", "rtt_min_ms", "armed_ms", "popt", "cal_us", "fail"}
        may_write = info.get("role") if info.get("expired") == "E3" else None
        for rr in ROLES:
            left = set(d["per_role"][rr]) if rr != may_write else set(d["per_role"][rr]) - fresh_keys
            if left:
                bad("M8", f"a retry left {sorted(left)} behind for {rr}")
        if any(any(d[f].values()) for f in ("committed", "submitted")) or d["t0_ms"] is not None:
            bad("M8", "a retry left a flag or t0 behind")
        if any(d["armed"][rr] for rr in ROLES if rr != may_write):
            bad("M8", "a retry left an armed flag behind")
    if info.get("stale"):
        if status != 409 or code != "stale_attempt":
            bad("M8", f"older attempt got {status} {code}, not 409 stale_attempt")
        cov[f"stale:{op['op']}"] += 1
    if info.get("stale") and without_seq(after) != without_seq(info["after_load"]):
        bad("M8", "older attempt changed the document")
    if d["t0_ms"] is not None:   # data in this attempt really is from this attempt
        for rr in ROLES:
            p = d["per_role"][rr]
            if "commit_b64" in p and decode_commit(base64.b64decode(p["commit_b64"]))["attempt"] != d["attempt"]:
                bad("M8", "a commit from another attempt is stored")
            if "transcript_b64" in p and decode_transcript(base64.b64decode(p["transcript_b64"]))["attempt"] != d["attempt"]:
                bad("M8", "a transcript from another attempt is stored")
    # M2 and terminal states
    if ctx.frozen is not None:
        fr = d["result"] or {}
        for k, v in ctx.frozen["result"].items():
            if fr.get(k) != v:
                bad("M2", f"result.{k} changed")
        if d["state"] != ctx.frozen["state"] or d["error"] != ctx.frozen["error"]:
            bad("M2", "state or error changed after the result was set")
    if before_doc["state"] in ("done", "aborted") and d["state"] != before_doc["state"]:
        bad("M1", f"left {before_doc['state']}")
    check_m9(ctx, d, before_doc, bad)
    # M10: first one stays
    if status == 200 and info.get("new_commit"):
        ctx.ledger[(d["attempt"], info["role"], "cm")] = info["new_commit"]
    if status == 200 and info.get("new_tx"):
        ctx.ledger[(before_doc["attempt"], info["role"], "tx")] = info["new_tx"]
    for (k_at, rr, what), lab in ctx.ledger.items():
        pr = None
        if d["attempt"] == k_at:
            pr = d["per_role"][rr]
        elif k_at < len(d["attempts"]):
            pr = d["attempts"][k_at].get("per_role", {}).get(rr)
        if pr is None:
            continue
        got = ctx.cm_label.get(pr.get("commit_b64")) if what == "cm" else ctx.tx_label.get(pr.get("transcript_b64"))
        if got != lab:
            bad("M10", f"{rr} at attempt {k_at}: stored {what} {got} is not the first accepted {lab}")
    # M3, M4, M11, V1, V5, V7 at the moment a result appears
    new_result = before_doc["result"] is None and d["result"] is not None
    if new_result:
        res = d["result"]
        ctx.frozen = {"result": {k: copy.deepcopy(v) for k, v in res.items() if k != "zk"}, "state": d["state"], "error": d["error"]}
        row = d["attempts"][-1]
        if res["verdict"] == "NEAR":
            if op["op"] != "transcript" or status != 200 or row["outcome"] != "verdict" or "combine" not in info:
                bad("M4", f"NEAR from {op['op']}, row {row['outcome']}")
            if row["verdict"] != "NEAR":
                bad("M4", "row verdict is not NEAR")
            check_m3(ctx, d, bad)
            check_m11(ctx, d, bad)
        elif res["verdict"] != "NOT_NEAR":
            bad("M4", f"verdict {res['verdict']}")
        check_record_shape(res, op, bad)
        changed = diff({k: v for k, v in res.items() if k != "zk"}, want_record(ctx, d))
        if changed:
            bad("M1", f"the record differs from the document: {str(changed)[:400]}")
        check_v7(ctx, d, bad, cov)
        check_v5(ctx, d, bad, cov)
    if "combine" in info:   # V1 to V4: combine ran. The real outcome must be what the integer rules say.
        out = info["combine"]
        check_numbers_of_step(ctx, op, info, bad, cov)
        rows = d["attempts"]
        last = rows[-1] if rows else {}
        if out["verdict"] == "NEAR" and (d["result"] or {}).get("verdict") != "NEAR":
            bad("V1", f"rules say NEAR, server stored {(d['result'] or {}).get('verdict')} {last.get('reason')}")
        if out["verdict"] != "NEAR" and (d["result"] or {}).get("verdict") == "NEAR":
            bad("V1", f"rules say {out['reason']}, server stored NEAR")
        if out["reason"] is not None and last.get("reason") != out["reason"]:
            bad("V1", f"rules say {out['reason']}, row says {last.get('reason')}")
        if out["reason"] == "self_timestamp_mismatch" and last.get("by") != out["by"]:
            bad("V1", f"self check by {last.get('by')}, rules say {out['by']}")
        if out["verdict"] is not None and (d["result"] or {}).get("flight_cm") != out["flight"]:
            bad("V1", "shown flight differs")
    if info.get("v5_live"):
        cov["V5:live"] += 1
        if status != 400 or code != "transcript_mismatch" or d["state"] != "done":
            bad("V5", f"a transcript signed with the other role got {status} {code}, state {d['state']}")
    # M5, M6, and the responses
    scan_response(ctx, op, status, text, body, d, info, bad)
    if status == 200 and op["op"] in VIEW_OPS and isinstance(body, dict):
        check_view(ctx, body, pred, info.get("view_role"), op, bad)
    if status == 200 and op["op"] == "transcript" and isinstance(body, dict):
        if body != {"accepted": True, "state": pred["state"], "attempt": pred["attempt"]}:
            bad("TABLE", f"transcript response {body}")
    if status == 200 and op["op"] == "result":
        if body != d["result"]:
            bad("TABLE", "result route differs from the stored result")

    op_view = {k: v for k, v in op.items() if not k.startswith("_")}
    if trace is not None:
        trace.write(json.dumps({"session": ctx.idx, "step": len(ctx.ops), "now": now, "op": op_view, "status": status, "code": code,
                                "before": before_m, "after": after, "x": trace_extra(ctx, d), "resp": resp_digest(ctx, op, status, body, d, info)}, sort_keys=True) + "\n")
    ctx.ops.append((now, op))
    tally(ctx, op, status, code, info, d, cov, now)
    if props:
        names = sorted({p for p, _ in props})
        if ctx.watch and ctx.watch not in names:   # a mutation run: follow the real server and look for the named property
            ctx.model = after
            cov["mutation_steps_off_table"] += 1
            return True
        lines = "\n".join(f"  [{p}] {m}" for p, m in props[:12])
        raise WalkFail(names, f"session {ctx.idx} step {len(ctx.ops)} now {now}\n  op {json.dumps(op_view)}\n{lines}")
    ctx.model = pred
    return True


def diff(a, b, path=""):
    if isinstance(a, dict) and isinstance(b, dict):
        out = {}
        for k in set(a) | set(b):
            out.update(diff(a.get(k), b.get(k), f"{path}.{k}"))
        return out
    return {} if a == b else {path: [a, b]}


