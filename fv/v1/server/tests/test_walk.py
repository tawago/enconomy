PERSONAS = [(0.98, 40), (0.88, 30), (0.6, 20), (0.25, 10)]
CLASSES = [("near", 45), ("far", 8), ("impossible", 12), ("tie60", 5), ("tie20", 5), ("just_in", 5), ("extreme", 3), ("self_bad_A", 5), ("self_bad_B", 5),
           ("self_edge_ok", 3), ("self_edge_bad", 3), ("phone_fail", 3)]
COMMON_RATES = [48000, 48000, 44100, 36000, 96000, 68600, 48020, 36015, 44101, 95999]


def weighted(rng, pairs):
    return rng.choices([p[0] for p in pairs], weights=[p[1] for p in pairs])[0]


class Plan:
    """What a session means to do, drawn once. Drawn from rng only, never from a secret."""

    def __init__(self, rng, v2_share):
        self.rng = rng
        self.edge = rng.choices([None, "gate", "deadline", "age", "token", "late_e2", "silent"], weights=[72, 8, 6, 4, 4, 2, 4])[0]
        self.p_good = 1.0 if self.edge in ("gate", "deadline", "age", "token") else weighted(rng, PERSONAS)
        self.e2_at = rng.choice([0, 1])
        # How often this session sends a bad op right where it bites: while started, by a real member.
        self.focus = rng.choice([0, 0, 0, 0.15, 0.35]) if self.edge is None else 0
        if self.edge == "late_e2":
            self.p_good = 1.0
        self.popt = {"A": 2 if rng.random() < v2_share else 1, "B": 2 if rng.random() < v2_share else 1}
        self.silent = rng.choice(["A", "B", None])
        self.guest = "C" if rng.random() < 0.04 else "B"
        self.cls = {}
        self.rates = {}
        self.rec = rng.randint(1, 3)
        self.halves = {}
        self.tail = rng.randint(0, 5)
        # While one phone has submitted and the other hasn't: how often the other one sends something that keeps the session live.
        self.peek = rng.choice([0, 0.5, 0.7]) if self.edge in (None, "silent") else 0
        # A phone that commits and submits before the other one commits.
        self.lead = rng.choice(ROLES) if self.edge is None and rng.random() < 0.2 else None
        # A phone whose device row gets a new calibration after arm, before combine. The snapshot must win (spec V4).
        self.cal_move = rng.choice(ROLES) if self.edge is None and rng.random() < 0.15 else None

    def klass(self, at):
        if at not in self.cls:
            self.cls[at] = "near" if self.edge in ("deadline", "age") else weighted(self.rng, CLASSES)
            if self.edge == "late_e2" and at == 0 and self.e2_at == 1:
                self.cls[at] = "impossible"
        return self.cls[at]

    def rate(self, at, role):
        if (at, role) not in self.rates:
            c = self.klass(at)
            if c in ("tie60", "tie20"):
                k = self.rng.randint(21, 55)
                self.rates[(at, "A")] = 1715 * k
                self.rates[(at, "B")] = 1715 * k if self.rng.random() < 0.5 else self.rng.choice(COMMON_RATES)
            else:
                self.rates[(at, role)] = self.rng.choice(COMMON_RATES)
        return self.rates[(at, role)]

    def numbers(self, at, sra, srb, cala, calb):
        """(hA, hB, dA, dB) for this attempt, from the rates armed. Cached, so both phones sign one plan."""
        key = (at, sra, srb, cala, calb)
        if key in self.halves:
            return self.halves[key]
        rng, c = self.rng, self.klass(at)

        def from_flight(f, hb):
            return int(round((f / 17150 + hb / srb) * sra))

        def mid(sr, cal):
            return int(round(cal * sr / 1e6))

        hb = rng.randint(-3000, 3000)
        ha = from_flight(rng.uniform(-18, 58), hb)
        da, db = mid(sra, cala) + rng.randint(-5, 5), mid(srb, calb) + rng.randint(-5, 5)
        if c == "far":
            ha = from_flight(rng.uniform(61, 40000), hb)
        elif c == "impossible":
            ha = from_flight(rng.uniform(-40000, -21), hb)
        elif c == "just_in":
            ha = from_flight(rng.choice([rng.uniform(59.0, 59.99), rng.uniform(-19.99, -19.0), 60.0, -20.0]), hb)
        elif c in ("tie60", "tie20"):
            mult = 6 if c == "tie60" else -2
            if sra % 1715 == 0 and sra == srb:
                j = rng.randint(-500, 500)
                ha, hb = sra // 1715 * mult + j, j
            elif sra % 1715 == 0:
                ha, hb = sra // 1715 * mult, 0
        elif c == "extreme":
            hb = rng.choice([-2 ** 31, 2 ** 31 - 1])
            ha = from_flight(rng.uniform(-18, 58), hb)
            ha = max(-2 ** 31, min(2 ** 31 - 1, ha))
        elif c in ("self_bad_A", "self_bad_B"):
            off = rng.choice([1, -1]) * rng.randint(SELF_TOL_MS * max(sra, srb) // 1000 + 1, 100000)
            if c == "self_bad_A":
                da += off
            else:
                db += off
        elif c in ("self_edge_ok", "self_edge_bad"):
            def edge(sr, cal, up):
                # the largest (or smallest) delta that passes
                top = (cal * sr + SELF_TOL_MS * 1000 * sr) // 1_000_000
                low = -((-(cal * sr) + SELF_TOL_MS * 1000 * sr) // 1_000_000)
                return (top + (1 if c == "self_edge_bad" else 0)) if up else (low - (1 if c == "self_edge_bad" else 0))
            who = rng.choice("AB")
            if who == "A":
                da = edge(sra, cala, rng.random() < 0.5)
            else:
                db = edge(srb, calb, rng.random() < 0.5)
        self.halves[key] = (ha, hb, da, db)
        return self.halves[key]


def base_op(kind, actor, tag=None, **kw):
    op = {"op": kind, "actor": actor, "auth": "ok"}
    if tag:
        op["tag"] = tag
    op.update(kw)
    return op


def honest_commit_fields(ctx, plan, role, version=None):
    m = ctx.model
    armed = m["per_role"][role].get("popt", plan.popt[role])
    return {"role": role, "attempt": m["attempt"], "nonce": "ok", "version": armed if version is None else version, "rec": plan.rec}


def honest_tx_fields(ctx, plan, role):
    m = ctx.model
    at = m["attempt"]
    pa, pb = m["per_role"]["A"], m["per_role"]["B"]
    sra, srb = pa.get("sr", 48000), pb.get("sr", 48000)
    ca = 0 if pa.get("popt") == 2 else pa.get("cal", 0)
    cb = 0 if pb.get("popt") == 2 else pb.get("cal", 0)
    ha, hb, da, db = plan.numbers(at, sra, srb, ca, cb)
    actor = phone_of(m, role) or plan.guest
    other = phone_of(m, OTHER[role]) or "C"
    me = m["per_role"][role]
    return {"role": role, "attempt": at, "nonce": "ok", "pk_self": actor, "pk_partner": other, "sr": me.get("sr", 48000), "half": ha if role == "A" else hb,
            "delta": da if role == "A" else db, "commit": "ok", "rec": "ok", "version": me.get("popt", plan.popt[role]), "v2_delta": "ok", "v2_cc": "ok"}


def good_op(ctx, plan):
    """The next step an honest pair would take, or None if the session is over."""
    m, rng = ctx.model, ctx.rng
    st = m["state"]
    if st == "created":
        return base_op("join", plan.guest, "good", token="ok", body="ok")
    guest = m["guest"]
    if st == "joined":
        r = "A" if not m["confirmed"]["A"] else "B"
        return base_op("confirm", phone_of(m, r), "good")
    if st == "confirmed":
        r = rng.choice([x for x in ROLES if not m["armed"][x]])
        return base_op("arm", phone_of(m, r), "good", attempt=m["attempt"], sample_rate=plan.rate(m["attempt"], r),
                       rtt_min_ms=rng.choice([0, 5, 12.5, 300]), popt=plan.popt[r], body="ok")
    if st == "started":
        if plan.klass(m["attempt"]) == "phone_fail" and rng.random() < 0.5:
            r = rng.choice(ROLES)
            return base_op("fail", phone_of(m, r), "phone_fail", attempt=m["attempt"], body="ok",
                           reason=rng.choice(["capture_failed", "glitch", "self_not_heard", "self_timestamp_mismatch", "partner_not_heard"]))
        if plan.lead and not m["submitted"][plan.lead]:
            r = plan.lead
            if m["committed"][r]:
                return base_op("transcript", phone_of(m, r), "good", body="ok", fields=honest_tx_fields(ctx, plan, r))
            return base_op("commit", phone_of(m, r), "good", body="ok", fields=honest_commit_fields(ctx, plan, r))
        todo = [x for x in ROLES if not m["committed"][x]]
        if todo:
            r = rng.choice(todo)
            return base_op("commit", phone_of(m, r), "good", body="ok", fields=honest_commit_fields(ctx, plan, r))
        todo = [x for x in ROLES if not m["submitted"][x] and not (plan.edge == "silent" and x == plan.silent)]
        if todo:
            r = rng.choice(todo)
            return base_op("transcript", phone_of(m, r), "good", body="ok", fields=honest_tx_fields(ctx, plan, r))
    return None


