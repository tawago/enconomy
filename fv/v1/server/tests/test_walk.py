def find_keys(x, out):
    if isinstance(x, dict):
        for k, v in x.items():
            out.append((k, v))
            find_keys(v, out)
    elif isinstance(x, list):
        for v in x:
            find_keys(v, out)


def check_m9(ctx, d, prev, bad):
    st = d["state"]
    if d["attempt"] not in (0, 1):
        bad("M9", "attempt out of range")
    if d["host_device_id"] is None or d["host_device_id"] == d["guest_device_id"]:
        bad("M9", "host unset or host = guest")
    for r in ROLES:
        if d["submitted"][r] and not d["committed"][r]:
            bad("M9", f"{r} submitted but not committed")
        if d["committed"][r] and not d["armed"][r]:
            bad("M9", f"{r} committed but not armed")
        p = d["per_role"][r]
        if d["committed"][r] and "commit_b64" not in p:
            bad("M9", f"{r} committed with no commit stored")
        if d["submitted"][r] and "transcript_b64" not in p:
            bad("M9", f"{r} submitted with no transcript stored")
        if d["armed"][r] != ("sample_rate" in p):
            bad("M9", f"{r} armed flag and stored rate disagree")
        if prev and prev["confirmed"][r] and not d["confirmed"][r]:
            bad("M9", f"{r} confirmed went back")
    if [a["attempt"] for a in d["attempts"]] != list(range(len(d["attempts"]))):
        bad("M9", "attempts rows are not 0, 1, ...")
    if (d["result"] is not None) != (st == "done"):
        bad("M9", "result set and state done disagree")
    armed, committed, submitted, conf = [[d[f][r] for r in ROLES] for f in ("armed", "committed", "submitted", "confirmed")]
    if st == "created" and (d["guest_device_id"] is not None or any(armed + committed + submitted + conf) or d["t0_ms"] is not None or d["attempt"] != 0):
        bad("M9", "created row")
    if st == "joined" and (d["guest_device_id"] is None or all(conf) or any(armed + committed + submitted) or d["t0_ms"] is not None or d["attempt"] != 0):
        bad("M9", "joined row")
    if st == "confirmed" and (d["guest_device_id"] is None or not all(conf) or all(armed) or any(committed + submitted) or d["t0_ms"] is not None):
        bad("M9", "confirmed row")
    if st == "started":
        if d["guest_device_id"] is None or not all(conf + armed) or d["t0_ms"] is None or all(submitted):
            bad("M9", "started row")
        for r in ROLES:
            if "sample_rate" not in d["per_role"][r] or "popt" not in d["per_role"][r]:
                bad("M9", "started row: rate or popt missing")
    if st == "done":
        if d["finished_ms"] is None or d["error"] != d["result"]["reason"]:
            bad("M9", "done row")
        if d["attempts"][-1]["outcome"] == "verdict" and not all(submitted):
            bad("M9", "verdict without both transcripts")
    if st == "aborted":
        ok = d["result"] is None and ((d["error"] == "aborted" and d["finished_ms"] is not None) or (d["error"] == "timeout" and d["finished_ms"] is None))
        if not ok:
            bad("M9", "aborted row")


def check_m3(ctx, d, bad):
    """Every part of M3, read from the stored document with the enrolled keys."""
    k = d["result"]["attempt"]
    if k != d["attempt"]:
        bad("M3", "result attempt is not the session attempt")
    nonce = bytes.fromhex(d["nonce_hex"])
    host = bytes.fromhex(ctx.env.store.get_device(d["host_device_id"])["pubkey"])
    guest = bytes.fromhex(ctx.env.store.get_device(d["guest_device_id"])["pubkey"])
    pk = {"A": host, "B": guest}
    ts = {}
    for r in ROLES:
        p = d["per_role"][r]
        if not (d["committed"][r] and d["submitted"][r]):
            bad("M3", f"{r} not committed and submitted")
            return
        if (k, r, "cm") not in ctx.ledger or (k, r, "tx") not in ctx.ledger:
            bad("M3", f"{r}: commit or transcript was not accepted while attempt = {k}")
        craw, cs = base64.b64decode(p["commit_b64"]), base64.b64decode(p["commit_sig_b64"])
        traw, tsig = base64.b64decode(p["transcript_b64"]), base64.b64decode(p["sig_b64"])
        if not verify_raw(pk[r], craw, cs):
            bad("M3", f"{r} commit signature")
        if not verify_raw(pk[r], traw, tsig):
            bad("M3", f"{r} transcript signature")
        c, t = decode_commit(craw), decode_transcript(traw)
        if c["role"] != r or c["attempt"] != k or c["nonce"] != nonce:
            bad("M3", f"{r} commit fields")
        rk = "rec_root" if p.get("popt") == 2 else "rec_sha256"
        if (t["pk_self"] != pk[r] or t["pk_partner"] != pk[OTHER[r]] or t["role"] != r or t["attempt"] != k or t["nonce"] != nonce
                or t["commit_hash"] != hashlib.sha256(craw).digest() or t[rk] != c[rk]):
            bad("M3", f"{r} transcript fields")
        ts[r] = t
    a, b = ts["A"], ts["B"]
    if i_verdict(a["half"], a["sample_rate"], b["half"], b["sample_rate"]) != "near":
        bad("M3", f"NEAR but the numbers don't fit: {a['half']}/{a['sample_rate']} {b['half']}/{b['sample_rate']}")
    for r in ROLES:
        cal = 0 if d["per_role"][r].get("popt") == 2 else d["per_role"][r].get("cal_us", 0)
        if not i_self_ok(ts[r]["self_os_delta"], ts[r]["sample_rate"], cal):
            bad("M3", f"NEAR but {r}'s self check fails")


def check_m11(ctx, d, bad):
    now = ctx.clock()
    t0 = d["t0_ms"]
    if now > t0 + DEADLINE_MS:
        bad("M11", f"NEAR at t0 + {now - t0}")
    if now - d["created_ms"] > MAX_AGE_MS:
        bad("M11", f"NEAR at age {now - d['created_ms']}")
    if d["finished_ms"] != now:
        bad("M11", "finished_ms is not this step's clock")
    for r in ROLES:
        p = d["per_role"][r]
        if p["committed_ms"] < t0 + GATE_MS:
            bad("M11", f"{r} committed at t0 + {p['committed_ms'] - t0}")
        if t0 < p["armed_ms"] + T0_DELAY_MS:
            bad("M11", f"t0 is less than arm time + {T0_DELAY_MS}")


