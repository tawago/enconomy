def known_numbers(ctx, op, d, role):
    """The numbers an error may name: what this request sent, and what this phone already knows."""
    out = {d["attempt"] if d else 0, ctx.clock(), COMMIT_LEN - 1, TRANSCRIPT_LEN - 1, TRANSCRIPT2_LEN - 1}
    if ctx.sent_ts is not None:
        out.add(ctx.sent_ts)
    for k in ("attempt", "sample_rate"):
        if int_strict(op.get(k)):
            out.add(op[k])
    f = (op.get("eff") or {}).get("fields") or {}
    for k in ("attempt", "sr", "version"):
        if k in f:
            out.add(f[k])
    if SR_MIN <= f.get("sr", 0) <= SR_MAX:   # a v2 transcript's delta field: the right value, or the right value + 1
        out |= {popt2.delta(f["sr"]), (popt2.delta(f["sr"]) + 1) & 0xFFFF}
    if d and role:
        p = d["per_role"][role]
        out |= {p[k] for k in ("sample_rate", "popt") if k in p}
    return out


def check_error(ctx, op, body, d, role, bad):
    """An error body: only {error, detail}, a known wording, and no number the sender doesn't already know."""
    if not isinstance(body, dict) or set(body) != {"error", "detail"} or not isinstance(body["detail"], str):
        bad("M6", f"error body to {op['op']} is not just error and detail: {str(body)[:300]}")
        return
    code, detail = body["error"], body["detail"]
    for pat in ERROR_DETAILS.get(code, []):
        hit = re.fullmatch(pat, detail)
        if hit:
            extra = {int(g) for g in hit.groups() if g is not None} - known_numbers(ctx, op, d, role)
            if extra:
                bad("M6", f"{code} detail to {op['op']} names numbers the sender doesn't know: {detail[:300]!r}")
            return
    bad("M6", f"{code} detail to {op['op']} has an unknown wording: {detail[:300]!r}")


