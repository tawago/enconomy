# ---------------------------------------------------------------- the numbers, written independently of verdict.py

def i_verdict(ha, sra, hb, srb):
    """The integer test from spec V3. Returns "impossible", "far" or "near"."""
    n, s = ha * srb - hb * sra, sra * srb
    if 34300 * n <= -40 * s:
        return "impossible"
    if 34300 * n >= 120 * s:
        return "far"
    return "near"


def i_flight(ha, sra, hb, srb):
    return Fraction(34300, 2) * (Fraction(ha, sra) - Fraction(hb, srb))


def i_self_ok(d, sr, cal):
    return abs(d * 1_000_000 - cal * sr) <= SELF_TOL_MS * 1000 * sr


def i_bed_key(seed, role, attempt):
    return hashlib.sha256(f"pop-v1|{seed}|JBL250|{role}|{attempt}|bed".encode()).digest()


def i_combine(pr):
    """What combine must say about two stored per_role records."""
    for r in ROLES:
        p = pr[r]
        if not i_self_ok(p["delta"], p["sr"], 0 if p["popt"] == 2 else p["cal"]):
            return {"verdict": None, "reason": "self_timestamp_mismatch", "by": r, "flight": None}
    a, b = pr["A"], pr["B"]
    f = round(float(i_flight(a["half"], a["sr"], b["half"], b["sr"])), 2)
    v = i_verdict(a["half"], a["sr"], b["half"], b["sr"])
    if v == "impossible":
        return {"verdict": None, "reason": "impossible_flight", "by": None, "flight": f}
    if v == "far":
        return {"verdict": "NOT_NEAR", "reason": "too_far", "by": None, "flight": f}
    return {"verdict": "NEAR", "reason": None, "by": None, "flight": f}


