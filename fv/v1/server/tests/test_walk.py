def want_invite_b64url(ctx, d):
    """The 49-byte invite, written out here: magic, version, session id, token, expiry in seconds, host key hint."""
    raw = (b"POP1\x01" + bytes.fromhex(d["session_id"]) + bytes.fromhex(d["join_token"]) + struct.pack(">I", d["token_expires_ms"] // 1000)
           + hashlib.sha256(ctx.phones["A"].pub).digest()[:8])
    return base64.urlsafe_b64encode(raw).decode().rstrip("=")


def do_create(ctx, op, cov, trace):
    """A create. Bad ones store nothing. A good one starts the model."""
    before = ctx.env.count_sessions()
    want_store = op["create_body"] in ("empty", "object", "policy_none") and op["auth"] == "ok"
    r, rec = send(ctx, op)
    body = r.json()
    code = body.get("error") if r.status_code >= 400 else None
    if r.status_code >= 400:
        problems = []
        check_error(ctx, op, body, None, None, lambda p, m: problems.append((p, m)))
        if problems:
            raise WalkFail([p for p, _ in problems], f"create {op}: {problems}")
    if want_store:
        want = (200, None)
    elif op["auth"] != "ok":
        want = (401, m_auth(op, 0, None))
    elif op["create_body"] == "bad_policy":
        want = (400, "bad_policy")
    else:
        want = (400, "bad_request")
    if (r.status_code, code) != want:
        raise WalkFail(["TABLE"], f"create {op} got {r.status_code} {code}, table says {want}")
    now_count = ctx.env.count_sessions()
    if now_count != before + (1 if want_store else 0):
        raise WalkFail(["M14"], f"create {op}: the store went from {before} to {now_count}")
    cov[f"code:create:{code or 200}"] += 1
    after = None
    if want_store:
        if op["actor"] != "A":
            raise AssertionError("the host is phone A in this walk")
        ctx.sid = body["session_id"]
        d = ctx.env.store.get_session(ctx.sid)
        ctx.doc = d
        ctx.base = d["created_ms"]
        ctx.nonce, ctx.token, ctx.seed = bytes.fromhex(d["nonce_hex"]), d["join_token"], d["seed_hex"]
        ctx.doc_nonce_hex = d["nonce_hex"]
        ctx.model = new_model()
        after = abstract(ctx, d)
        ctx.last_auth["A"] = dict(rec, ts_rel=int(rec["headers"]["X-Pop-Ts"]) - ctx.base, first_rel=0)
        if without_seq(after) != without_seq(ctx.model) or after["seq"] != ctx.model["seq"]:
            raise WalkFail(["M1"], f"create: stored {after}")
        if d["context"] is not None or d["policy"] != {"human": "none"}:
            raise WalkFail(["TABLE"], "this walk is only about context=None, human=none")
        ctx.fixed = {k: copy.deepcopy(d[k]) for k in FIXED_KEYS}
        if d["host_device_id"] != ctx.phones["A"].device_id or d["created_ms"] != ctx.clock() or d["not_before"] != d["created_ms"] // 1000:
            raise WalkFail(["M1"], "create: host, created_ms or not_before")
        for k, n in (("session_id", 32), ("seed_hex", 64), ("nonce_hex", 64), ("join_token", 32)):
            if not re.fullmatch(f"[0-9a-f]{{{n}}}", d[k]):
                raise WalkFail(["M1"], f"create: {k} is not {n} hex digits")
        low = r.text.lower()
        for name, s in ctx.secret_forms():
            if s.lower() in low:
                raise WalkFail(["M5"], f"{name} in the create response")
        want_invite = want_invite_b64url(ctx, d)
        ctx.invite = want_invite
        if body.get("invite_b64url") != want_invite or body.get("invite_qr") != "pop1:" + want_invite:
            raise WalkFail(["M5"], "create: the invite holds something other than session id, token, expiry and host hint")
        want_body = {"session_id": d["session_id"], "join_token": d["join_token"], "expires_at_ms": d["token_expires_ms"], "invite_b64url": want_invite,
                     "invite_qr": "pop1:" + want_invite, "nonce": d["nonce_hex"], "not_before": d["not_before"], "context": None, "policy": {"human": "none"}}
        changed = diff(body, want_body)
        if changed:
            raise WalkFail(["M6"], f"create response differs: {sorted(changed)}")
        if len({i_bed_key(ctx.seed, x, k) for x in ROLES for k in (0, 1)}) != 4:
            raise WalkFail(["M8"], "two bed keys are equal")
        for x in ROLES:
            for k in (0, 1):
                if jbl250.bed_key(ctx.seed, x, k) != i_bed_key(ctx.seed, x, k):
                    raise WalkFail(["M8"], "bed_key is not the derivation in spec C11")
        ctx.seen_states.add("created")
        cov["state:created"] += 1
    if trace is not None:
        trace.write(json.dumps({"session": ctx.idx, "step": len(ctx.ops), "now": 0, "op": dict(op, cal=ctx.cal), "status": r.status_code, "code": code, "before": None,
                                "after": after, "x": trace_extra(ctx, d) if want_store else None,
                                "resp": resp_digest(ctx, op, r.status_code, body, ctx.doc, {}) if want_store else None}, sort_keys=True) + "\n")
    ctx.ops.append((0, op))


def set_cal(ctx, op, trace):
    """Not a route. The device row's calibration moves, which arm must snapshot (spec V4). Enrolment itself is out of scope."""
    ctx.cal[op["actor"]] = op["cal_us"]
    ctx.env.store.put_device(dict(ctx.phones[op["actor"]].row, cal_us=op["cal_us"]))
    if trace is not None:
        trace.write(json.dumps({"session": ctx.idx, "step": len(ctx.ops), "now": ctx.rel(), "op": op, "status": 0, "code": None,
                                "before": ctx.model, "after": ctx.model, "resp": None}, sort_keys=True) + "\n")
    ctx.ops.append((ctx.rel(), op))


def run_session(env, idx, seed, cov, trace, script=None, v2_share=0.2, watch=None):
    """One session. With a script: run those (time, op) pairs instead of drawing them. Used for minimizing."""
    rng = random.Random(f"{seed}:{idx}")
    ctx = Ctx(env, idx, rng)
    ctx.watch = watch
    try:
        walk_session(ctx, rng, cov, trace, script, v2_share)
    except WalkFail as e:
        e.ops = ctx.ops
        raise
    return ctx


def walk_session(ctx, rng, cov, trace, script, v2_share):
    plan = Plan(rng, v2_share)
    cov["sessions"] += 1
    if script is not None:
        do_create(ctx, base_op("create", "A", create_body="object"), cov, None)
        for now, op in script:
            ctx.set_rel(max(now, ctx.rel()))
            if op["op"] == "set_cal":
                set_cal(ctx, op, None)
            else:
                one_step(ctx, op, cov, None)
        return
    for _ in range(rng.choice([0, 0, 0, 1, 2])):
        roll = rng.random()
        if roll < 0.7:
            op = base_op("create", "A", "bad_create", create_body=rng.choice(["bad_json", "not_object", "bad_policy"]))
        else:
            op = base_op("create", "A", "bad_create_auth", create_body="object", auth=rng.choice(["wrong_key", "tamper", "stale_old", "missing", "bad_sig_b64", "unknown_device"]))
        do_create(ctx, op, cov, trace)
    do_create(ctx, base_op("create", "A", "good", create_body=rng.choice(["empty", "object", "object", "policy_none"])), cov, trace)
    tail = plan.tail
    for _ in range(120):
        ctx.set_rel(max(next_time(ctx, plan), ctx.rel()))
        over = ctx.model["state"] in ("done", "aborted")
        if plan.cal_move and ctx.model["state"] == "started":
            p = ctx.model["per_role"][plan.cal_move]
            if p.get("popt") == 1:   # far past the 50 ms tolerance, so an honest delta would fail against the live row
                set_cal(ctx, {"op": "set_cal", "actor": phone_of(ctx.model, plan.cal_move), "cal_us": p["cal"] + 100000, "tag": "cal_move"}, trace)
                plan.cal_move = None
        if over:
            if tail <= 0:
                break
            tail -= 1
        op = None
        if not over and peek_ready(ctx) and rng.random() < plan.peek:
            op = peek_op(ctx, plan)
        elif not over and ctx.model["state"] == "started" and rng.random() < plan.focus:
            op = focus_op(ctx, plan)
        elif not over and rng.random() < plan.p_good:
            op = good_op(ctx, plan)
        if op is None:
            if not over and plan.edge in ("gate", "deadline", "age", "token") and ctx.model["state"] == "started":
                op = base_op("view", "A", "wait", query="")
            else:
                op = noise_op(ctx, plan)
        if op["op"] == "set_cal":
            set_cal(ctx, op, trace)
            continue
        one_step(ctx, op, cov, trace)


def minimize(env, idx, seed, ops, props):
    """Removes steps while the same property still breaks. Plain greedy. At most 300 tries."""
    cov = Counter()
    target = set(props)
    ops = [o for o in ops if o[1]["op"] != "create"]
    tries, size = 0, max(1, len(ops) // 2)

    def still(script):
        nonlocal tries
        tries += 1
        try:
            run_session(env, idx, seed, cov, None, script=script)
        except WalkFail as e:
            return bool(target & set(e.props))
        return False

    while size >= 1 and tries < 300:
        i, changed = 0, False
        while i < len(ops) and tries < 300:
            shorter = ops[:i] + ops[i + size:]
            if still(shorter):
                ops, changed = shorter, True
            else:
                i += size
        if size == 1 and not changed:
            break
        size = max(1, size // 2)
    return ops


def run_walk(env, sessions, seed, cov, trace=None, shrink=False, v2_share=0.2, watch=None):
    """Runs the sessions. watch: for a mutation test, keep going until that property breaks."""
    for i in range(sessions):
        try:
            run_session(env, i, seed, cov, trace, v2_share=v2_share, watch=watch)
        except WalkFail as e:
            if shrink:
                small = minimize(env, i, seed, e.ops, e.props)
                e.text += f"\n  minimized to {len(small)} steps:\n" + "\n".join(
                    f"    t={t} {json.dumps({k: v for k, v in o.items() if not k.startswith('_')})}" for t, o in small)
                e.args = (e.text,)
            raise


