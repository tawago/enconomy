def real_cc(ctx, cc, role):
    """Which code commit these bytes are, among those of this session at the rates armed in this attempt.
    Two close rates can give the very same bytes (95999 and 96000 do), so this asks about `role`'s own rate first. Two equal labels
    still always mean equal bytes. Two different labels could be equal bytes, which a replay would show as a mismatch and not hide."""
    mine = ctx.doc["per_role"][role].get("sample_rate")
    rates = {ctx.doc["per_role"][r].get("sample_rate") for r in ROLES} - {None}
    for sr in sorted(rates, key=lambda x: (x != mine, x)):
        for r in ROLES:
            for k in (0, 1):
                if cc.hex() == ctx.want_code_commit(r, k, sr):
                    return {"sr": sr, "role": r, "attempt": k}
    return "x:" + cc.hex()


def real_transcript(ctx, raw):
    try:
        t = decode_transcript(raw)
    except ValueError:
        return None
    keys = {p.pub: n for n, p in ctx.phones.items()}
    h = t["commit_hash"].hex()
    v2 = version_of(t) == 2
    return {"role": t["role"], "attempt": t["attempt"], "nonce": real_name(ctx, t["nonce"], {ctx.nonce: "ok"}),
            "pk_self": real_name(ctx, t["pk_self"], keys), "pk_partner": real_name(ctx, t["pk_partner"], keys), "sr": t["sample_rate"],
            "half": t["half"], "rec": int.from_bytes(t[REC_KEY[version_of(t)]], "big"), "delta": t["self_os_delta"],
            "commit_hash": ctx.cm_hash.get(h, "x:" + h), "version": version_of(t), "v2_delta": t["delta"] if v2 else None,
            "play_frame_position": t["play_frame_position"], "play_nano_time": t["play_nano_time"], "rec_frame0_nano_time": t["rec_frame0_nano_time"],
            "a_self": t["a_self"] if v2 else None, "p_partner": t["p_partner"] if v2 else None,
            "cc": real_cc(ctx, t["code_commit"], t["role"]) if v2 else None}


def sound_id(ctx, role, attempt, want, got):
    """Whose sound is this? want(r, k) is the real generator's. Own role and attempt first, so the common case costs one comparison."""
    for r, k in sorted(((r, k) for r in ROLES for k in (0, 1)), key=lambda x: x != (role, attempt)):
        if got == want(r, k):
            return f"{r}{k}"
    return "?"


def resp_digest(ctx, op, status, body, d, info):
    """The parts of a 200 body that the Lean Resp also has. Read from the response, not the document."""
    if status != 200 or not isinstance(body, dict):
        return None
    kind = op["op"]
    if kind in VIEW_OPS:
        def dev(x):
            return None if x is None else {"dev": ctx.names.get(x["device_id"], "?"), "pk": {p.pub.hex(): n for n, p in ctx.phones.items()}.get(x["pubkey"], "?"), "cal": x["cal_us"]}
        lf = body["last_failure"]
        res = body["result"]
        return {"kind": "view", "sid": same(body["session_id"], ctx.sid), "state": body["state"], "attempt": body["attempt"], "seq": body["seq"], "role": body["role"],
                "nonce": None if body["nonce"] is None else ("ok" if body["nonce"] == ctx.doc_nonce_hex else "?"),
                "self": dev(body["self"]), "partner": dev(body["partner"]), "confirmed": body["confirmed"], "armed": body["armed"],
                "committed": body["committed"], "submitted": body["submitted"], "popt": body["popt"],
                "t0": None if body["t0_ms"] is None else body["t0_ms"] - ctx.base, "error": body["error"],
                "last_failure": None if lf is None else {k: lf[k] for k in ("attempt", "reason", "by")},
                "result": None if res is None else full_record(ctx, res)}
    role = info.get("role")
    if kind == "arm":
        k, sr = body["attempt"], body["sample_rate"]
        out = {"kind": "arm", "attempt": k, "sr": sr, "play": sound_id(ctx, role, k, lambda r, a: ctx.play(r, a, sr), body["play"]),
               "own_bed": sound_id(ctx, role, k, lambda r, a: ctx.bed(r, a, sr), body["own_bed"]), "own_code": None, "delta": body.get("delta")}
        if "own_code" in body:
            out["own_code"] = sound_id(ctx, role, k, lambda r, a: ctx.code(r, a, sr), body["own_code"])
        return out
    if kind == "commit":
        k, sr, other = d["attempt"], d["per_role"][role]["sample_rate"], OTHER[role]
        out = {"kind": "commit", "partner_bed": sound_id(ctx, other, k, lambda r, a: ctx.bed(r, a, sr), body["partner_bed"]), "partner_code": None, "cc": None}
        if "partner_code" in body:
            out["partner_code"] = sound_id(ctx, other, k, lambda r, a: ctx.code(r, a, sr), body["partner_code"])
        if body.get("code_commit") is not None:
            out["cc"] = real_cc(ctx, bytes.fromhex(body["code_commit"]), role)
        return out
    if kind == "transcript":
        return {"kind": "accepted", "accepted": body["accepted"], "state": body["state"], "attempt": body["attempt"]}
    if kind == "result":
        return dict(full_record(ctx, body), kind="record")
    if kind == "create":
        return {"kind": "created", "token_exp": body["expires_at_ms"] - ctx.base, "sid": same(body["session_id"], ctx.sid),
                "token": same(body["join_token"], ctx.token), "nonce": same(body["nonce"], ctx.doc_nonce_hex)}
    raise AssertionError(kind)


def route(ctx, op):
    """(method, path, body bytes) for an op."""
    kind = op["op"]
    sid = ctx.sid if ctx.sid else "0" * 32
    if op.get("sid") == "upper":
        sid = sid.upper()
    elif op.get("sid") == "unknown":
        sid = "f" * 32
    p = f"/v1/session/{sid}"
    if kind == "create":
        return "POST", "/v1/session", {"empty": b"", "object": b"{}", "policy_none": b'{"policy":{"human":"none"}}', "bad_json": b"{",
                                       "not_object": b"[1]", "bad_policy": b'{"policy":{"human":"nope"}}'}[op["create_body"]]
    if kind == "view":
        return "GET", p + (f"?{op['query']}" if op.get("query") else ""), b""
    if kind == "result":
        return "GET", p + "/result", b""
    if kind in ("confirm", "abort"):
        return "POST", f"{p}/{kind}", b"{}"
    if kind == "join":
        tok = {"ok": ctx.token, "upper": (ctx.token or "").upper(), "wrong": "0" * 32}[op["token"]]
        body = {"join_token": tok}
    elif kind == "arm":
        body = {k: op[k] for k in ("attempt", "sample_rate", "rtt_min_ms", "popt")}
    elif kind == "fail":
        body = {k: op[k] for k in ("attempt", "reason")}
    else:
        body = op["_body"]
    raw = json.dumps(body).encode()
    if op.get("body") == "bad_json":
        raw = b"{bad"
    elif op.get("body") == "bad_shape":
        raw = b"[1]"
    return "POST", f"{p}/{kind}", raw


def send(ctx, op):
    """Signs and sends. Returns the response. Remembers what auth saw, for a replay."""
    actor = op["actor"]
    a = op.get("auth", "ok")
    if a == "replay":
        last = ctx.last_auth[actor]
        ctx.sent_ts = int(last["headers"]["X-Pop-Ts"])
        return ctx.env.client.request(last["method"], last["path"], content=last["raw"], headers=last["headers"]), None
    method, path, raw = route(ctx, op)
    now = ctx.clock()
    ts = now + {"stale_old": -SKEW_MS - 1, "stale_new": SKEW_MS + 1, "edge_old": -SKEW_MS, "edge_new": SKEW_MS}.get(a, 0)
    ctx.sent_ts = ts
    sk = ctx.phones[actor].sk
    signed_body = raw
    if a == "wrong_key":
        sk = ctx.phones["C" if actor != "C" else "A"].sk
    elif a == "tamper":
        signed_body = raw + b" "
    sig = sign_raw(sk, request_message(method, path, signed_body, str(ts)))
    h = {"X-Pop-Device": ctx.phones[actor].device_id, "X-Pop-Ts": str(ts), "X-Pop-Sig": b64(sig), "content-type": "application/json"}
    if a == "unknown_device":
        h["X-Pop-Device"] = "ab" * 16
    elif a == "missing":
        h = {"content-type": "application/json"}
    elif a == "bad_sig_b64":
        h["X-Pop-Sig"] = "@@@"
    r = ctx.env.client.request(method, path, content=raw, headers=h)
    return r, {"method": method, "path": path, "raw": raw, "headers": h, "ts_rel": ts - ctx.base, "first_rel": ctx.rel()}


