def tally(ctx, op, status, code, info, d, cov, now):
    key = f"{op['op']}:{code or status}"
    cov[f"code:{key}"] += 1
    cov["steps"] += 1
    if code and code.startswith("auth_"):
        cov[f"auth:{code}"] += 1
    if op.get("auth") in ("edge_old", "edge_new") and info["auth_ok"]:
        cov[f"edge:auth_{op['auth']}_passes"] += 1
    if op.get("tag"):
        cov[f"tag:{op['tag']}:{code or status}"] += 1
    for s in (d["state"],):
        if s not in ctx.seen_states:
            ctx.seen_states.add(s)
            cov[f"state:{s}"] += 1
    if info.get("expired") and info.get("expired") not in ctx.reached:
        ctx.reached.add(info["expired"])
        cov[f"expire:{info['expired']}"] += 1
        if info["expired"] == "E3":
            last = d["attempts"][-1] if d["attempts"] else {}
            cov[f"expire:E3:by={last.get('by')}"] += 1
    if op["op"] == "commit" and status == 200 and info.get("new_commit"):
        t = now - ctx.model["t0"]
        if t == GATE_MS:
            cov["edge:commit_at_gate"] += 1
    if op["op"] == "commit" and code == "too_early" and now - ctx.model["t0"] == GATE_MS - 1:
        cov["edge:too_early_at_gate_minus_1"] += 1
    if op["op"] == "join" and status == 200 and now == TOKEN_TTL_MS:
        cov["edge:join_at_token_expiry"] += 1
    if info.get("expired") == "E1" and now == TOKEN_TTL_MS + 1:
        cov["edge:E1_one_ms_late"] += 1
    if info.get("expired") == "E2" and now == MAX_AGE_MS + 1:
        cov["edge:E2_one_ms_late"] += 1
    if info.get("expired") == "E3" and now == (ctx.model["t0"] or 0) + DEADLINE_MS + 1:
        cov["edge:E3_one_ms_late"] += 1
    if "combine" in info:
        ks = (ctx.model["per_role"]["A"].get("popt"), ctx.model["per_role"]["B"].get("popt"))
        cov[f"combine:popt{ks[0]}+{ks[1]}"] += 1
        pair = info["pair"]
        live = {r: dict(pair[r], cal=ctx.cal[phone_of(ctx.model, r)] or 0) for r in ROLES}
        if i_combine(live) != info["combine"]:   # the moment V4's snapshot matters: reading the live row would change this outcome
            cov["cal_moved:outcome_differs"] += 1
        p = pred_pair(ctx, op, info)
        if p == 60:
            cov["edge:flight_exactly_60"] += 1
        if p == -20:
            cov["edge:flight_exactly_minus_20"] += 1
    if d["result"] is not None and "result" not in ctx.reached:
        ctx.reached.add("result")
        res, row = d["result"], d["attempts"][-1]
        k = res["attempt"]
        cov[f"verdict:{res['verdict']}"] += 1
        cov[f"end:{row['outcome']}:{res['reason'] or 'near'}:attempt{k}"] += 1
        if res["verdict"] == "NEAR":
            t0 = d["t0_ms"] - ctx.base
            if now == t0 + DEADLINE_MS:
                cov["edge:near_at_deadline"] += 1
            if now == MAX_AGE_MS:
                cov["edge:near_at_max_age"] += 1
            popts = (d["per_role"]["A"].get("popt"), d["per_role"]["B"].get("popt"))
            cov[f"near:popt{popts[0]}+{popts[1]}"] += 1
    r = info.get("role")
    if r and d["state"] in LIVE and "half" in d["per_role"][OTHER[r]]:   # the moment M6 is about
        kind = None
        if status >= 400:
            kind = "error"
            cov[f"live_half_code:{op['op']}:{code}"] += 1
        elif op["op"] == "arm":
            kind = "arm_repeat"
        elif op["op"] == "commit":
            kind = "commit_first" if info.get("new_commit") else "commit_repeat"
        elif op["op"] == "view":
            kind = "view"
        if kind:
            cov[f"live_half:{kind}"] += 1
    if d["state"] == "aborted" and "aborted" not in ctx.reached:
        ctx.reached.add("aborted")
        cov[f"end:aborted:{d['error']}:attempt{d['attempt']}"] += 1
    if d["attempt"] == 1 and "retry" not in ctx.reached:
        ctx.reached.add("retry")
        cov["sessions:retried"] += 1
        cov[f"retry:{d['attempts'][0]['reason']}"] += 1


def pred_pair(ctx, op, info):
    """The exact flight of the pair combine just saw, or None. Read from the step's own transcript registry."""
    rr = info.get("role")
    pr = ctx.model["per_role"]
    mine = op["eff"]["fields"]
    theirs = pr[OTHER[rr]]
    a = (mine["half"], mine["sr"]) if rr == "A" else (theirs["half"], theirs["sr"])
    b = (mine["half"], mine["sr"]) if rr == "B" else (theirs["half"], theirs["sr"])
    return i_flight(a[0], a[1], b[0], b[1])


