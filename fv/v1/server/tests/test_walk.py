def flags():
    return {"A": False, "B": False}


def new_model():
    return {"state": "created", "attempt": 0, "seq": 1, "guest": None, "confirmed": flags(), "armed": flags(), "committed": flags(),
            "submitted": flags(), "t0": None, "token_exp": TOKEN_TTL_MS, "finished": None, "error": None, "last_failure": None,
            "per_role": {"A": {}, "B": {}}, "attempts": [], "result": None}


def role_of(m, phone):
    return "A" if phone == "A" else ("B" if phone == m["guest"] else None)


def phone_of(m, role):
    return "A" if role == "A" else m["guest"]


def m_record(m, verdict, reason, flight):
    devices, tx, txs, txh, cm, cms = {}, {}, {}, {}, {}, {}
    for r in ROLES:
        p = m["per_role"][r]
        devices[r] = {"half": p.get("half"), "sr": p.get("sr"), "popt": p.get("popt", 1), "cal": p.get("cal", 0)}
        if "tx" in p:
            tx[r], txs[r], txh[r] = p["tx"], p["txs"], p["txh"]
        if "cm" in p:
            cm[r], cms[r] = p["cm"], p["cms"]
    rows = []
    for a in m["attempts"]:
        row = {k: a.get(k) for k in ("attempt", "outcome", "reason", "by")}
        if a.get("outcome") == "verdict":
            row.update(verdict=a["verdict"], flight=a["flight"])
        rows.append(row)
    return {"verdict": verdict, "reason": reason, "flight": flight, "attempt": m["attempt"], "t0": m["t0"], "devices": devices,
            "tx": tx, "txs": txs, "txh": txh, "cm": cm, "cms": cms, "rows": rows}


def m_finalize(m, verdict, reason, flight, outcome, by, now):
    m["attempts"].append({"attempt": m["attempt"], "outcome": outcome, "reason": reason, "by": by, "verdict": verdict, "flight": flight,
                          "per_role": copy.deepcopy(m["per_role"]), "t0": m["t0"]})
    m["state"], m["error"], m["finished"] = "done", reason, now
    m["result"] = m_record(m, verdict, reason, flight)
    m["seq"] += 1


def m_failed(m, reason, by, now):
    if reason in RETRY and m["attempt"] + 1 < 2:
        m["attempts"].append({"attempt": m["attempt"], "outcome": "failed", "reason": reason, "by": by,
                              "per_role": copy.deepcopy(m["per_role"]), "t0": m["t0"]})
        m["last_failure"] = {"attempt": m["attempt"], "reason": reason, "by": by}
        m["attempt"] += 1
        m["state"], m["t0"] = "confirmed", None
        m["armed"], m["committed"], m["submitted"] = flags(), flags(), flags()
        m["per_role"] = {"A": {}, "B": {}}
        m["seq"] += 1
    else:
        m_finalize(m, "NOT_NEAR", reason, None, "failed", by, now)


def m_expire(m, now):
    """E1, E2, E3, in that order. Returns which fired."""
    if m["state"] == "created" and now > m["token_exp"]:
        m["state"], m["error"] = "aborted", "timeout"
        m["seq"] += 1
        return "E1"
    if m["state"] in LIVE and now > MAX_AGE_MS:
        m["state"], m["error"] = "aborted", "timeout"
        m["seq"] += 1
        return "E2"
    if m["state"] == "started" and now > m["t0"] + DEADLINE_MS:
        silent = [r for r in ROLES if not m["submitted"][r]]
        m_failed(m, "timeout", silent[0] if len(silent) == 1 else None, now)
        return "E3"
    return None


def m_auth(op, now, last):
    """The error code from auth, or None."""
    a = op.get("auth", "ok")
    if a == "missing" or a == "bad_sig_b64_missing":
        return "auth_bad_signature"
    if a == "unknown_device":
        return "auth_unknown_device"
    if a == "stale_old" or a == "stale_new":
        return "auth_stale"
    if a == "bad_sig_b64" or a == "wrong_key" or a == "tamper":
        return "auth_bad_signature"
    if a == "replay":
        return "auth_stale" if abs(now - last["ts_rel"]) > SKEW_MS else "auth_replay"
    return None


def int_strict(x):
    return isinstance(x, int) and not isinstance(x, bool)


def m_step(m0, op, now, cal, last_auth):
    """One request. Returns (new model, status, code, info). No server code is called here."""
    m = copy.deepcopy(m0)
    kind, actor = op["op"], op["actor"]
    info = {"auth_ok": False, "expired": None, "changed": False}
    if kind in BODY_OPS and op.get("body", "ok") == "bad_json":
        return m, 400, "bad_request", info
    err = m_auth(op, now, last_auth.get(actor))
    if err:
        return m, 401, err, info
    info["auth_ok"] = True
    if kind in BODY_OPS and op.get("body", "ok") == "bad_shape":
        return m, 400, "bad_request", info
    if kind == "view" and op.get("query") == "after=x":
        return m, 400, "bad_request", info
    if op.get("sid", "ok") == "unknown":
        return m, 404, "not_found", info
    info["expired"] = m_expire(m, now)
    if m != m0:
        info["after_load"] = copy.deepcopy(m)
    else:
        info["after_load"] = m0
    r = role_of(m, actor)
    if kind == "join":
        if actor == "A":
            return m, 400, "self_join", info
        if m["guest"] is not None:
            return m, 409, "already_joined", info
        if op["token"] == "wrong":
            return m, 403, "bad_token", info
        if m["state"] != "created":
            return m, 410, "token_expired", info
        m["guest"], m["state"] = actor, "joined"
        m["seq"] += 1
        info["view_role"] = "B"
        return m, 200, None, info
    if r is None:
        return m, 403, "not_member", info
    info["role"] = r
    info["view_role"] = r
    if kind == "view":
        return m, 200, None, info
    if kind == "result":
        return (m, 404, "no_result", info) if m["result"] is None else (m, 200, None, info)
    if kind == "confirm":
        if m["state"] == "confirmed" or (m["state"] == "joined" and m["confirmed"][r]):
            return m, 200, None, info
        if m["state"] != "joined":
            return m, 409, "bad_state", info
        m["confirmed"][r] = True
        if all(m["confirmed"].values()):
            m["state"] = "confirmed"
        m["seq"] += 1
        return m, 200, None, info
    if kind == "abort":
        if m["state"] in ("done", "aborted"):
            return m, 200, None, info
        m["state"], m["error"], m["finished"] = "aborted", "aborted", now
        m["attempts"].append({"attempt": m["attempt"], "outcome": "aborted", "reason": "aborted", "by": r})
        m["seq"] += 1
        return m, 200, None, info
    if kind == "arm":
        return m_arm(m, op, r, now, cal, info)
    if kind == "commit":
        return m_commit(m, op, r, now, info)
    if kind == "transcript":
        return m_transcript(m, op, r, now, info)
    if kind == "fail":
        return m_fail(m, op, r, now, info)
    raise AssertionError(kind)


def m_arm(m, op, r, now, cal, info):
    if m["state"] not in ("confirmed", "started"):
        return m, 409, "bad_state", info
    at, sr, rtt, popt = op["attempt"], op["sample_rate"], op["rtt_min_ms"], op["popt"]
    if not int_strict(at) or at != m["attempt"]:
        return m, 400, "bad_attempt", info
    if not int_strict(sr) or not SR_MIN <= sr <= SR_MAX:
        return m, 400, "bad_sample_rate", info
    if not isinstance(rtt, (int, float)) or isinstance(rtt, bool) or not 0 <= rtt <= MAX_RTT:
        return m, 400, "bad_request", info
    popt = 1 if popt is None else popt
    if not int_strict(popt) or popt not in (1, 2):
        return m, 400, "bad_request", info
    p = m["per_role"][r]
    if m["armed"][r]:
        if p["sr"] != sr or p["popt"] != popt:
            return m, 409, "bad_state", info
        info["material"] = True
        return m, 200, None, info
    if m["state"] != "confirmed":
        return m, 409, "bad_state", info
    m["per_role"][r] = {"sr": sr, "popt": popt, "cal": cal[op["actor"]] or 0}
    m["armed"][r] = True
    if all(m["armed"].values()):
        m["state"], m["t0"] = "started", now + T0_DELAY_MS
    m["seq"] += 1
    info["material"] = True
    return m, 200, None, info


def sig_ok(e, actor):
    return e["sigkind"] in ("good", "flip") and e["signer"] == actor


def m_commit(m, op, r, now, info):
    e, actor = op["eff"], op["actor"]
    if m["state"] != "started":
        return m, 409, "bad_state", info
    if e["enc"] != "ok":
        return m, 400, "transcript_mismatch", info
    if not sig_ok(e, actor):
        return m, 400, "signature_invalid", info
    f = e["fields"]
    if f["role"] != r or f["attempt"] != m["attempt"] or f["nonce"] != "ok":
        return m, 400, "transcript_mismatch", info
    p = m["per_role"][r]
    if f["version"] != p["popt"]:
        return m, 400, "transcript_mismatch", info
    if m["committed"][r]:
        if p["cm"] != e["label"]:
            return m, 409, "already_committed", info
        info["reveal"] = True
        return m, 200, None, info
    if now < m["t0"] + GATE_MS:
        return m, 409, "too_early", info
    p.update(cm=e["label"], cms=e["sigl"], cmh=e["label"], rec=f["rec"])
    if f["version"] == 2:
        p["cc"] = True
    m["committed"][r] = True
    m["seq"] += 1
    info["reveal"] = True
    info["new_commit"] = e["label"]
    return m, 200, None, info


def m_transcript(m, op, r, now, info):
    e, actor = op["eff"], op["actor"]
    f = e["fields"]
    if e["enc"] == "ok" and f["attempt"] < m["attempt"] and sig_ok(e, actor) and m["state"] in ("confirmed", "started"):
        info["stale"] = True
        return m, 409, "stale_attempt", info
    if m["state"] != "started":
        return m, 409, "bad_state", info
    p = m["per_role"][r]
    if m["submitted"][r]:
        if p["tx"] == e["label"] and p["txs"] == e["sigl"]:
            info["accepted"] = True
            return m, 200, None, info
        return m, 409, "already_submitted", info
    if not m["committed"][r]:
        return m, 409, "bad_state", info
    why = None
    if e["enc"] != "ok":
        why = "transcript_mismatch"
    elif not sig_ok(e, actor):
        why = "signature_invalid"
    elif f["version"] != p["popt"]:
        why = "transcript_mismatch"
    elif f["pk_self"] != actor:
        why = "signature_invalid"
    elif f["role"] != r:
        why = "transcript_mismatch"
        info["v5_live"] = True
    elif f["nonce"] != "ok" or f["attempt"] != m["attempt"] or f["pk_partner"] != phone_of(m, OTHER[r]) or f["sr"] != p["sr"]:
        why = "transcript_mismatch"
    elif f["commit"] != "ok" or f["rec"] != "ok":
        why = "transcript_mismatch"
    elif f["version"] == 2 and (f["v2_delta"] != "ok" or f["v2_cc"] != "ok"):
        why = "transcript_mismatch"
    if why:
        m_finalize(m, "NOT_NEAR", why, None, "rejected", r, now)
        info["rejected"] = True
        return m, 400, why, info
    p.update(tx=e["label"], txs=e["sigl"], txh=e["label"], half=f["half"], delta=f["delta"])
    m["submitted"][r] = True
    info["accepted"] = True
    info["new_tx"] = e["label"]
    if not all(m["submitted"].values()):
        m["seq"] += 1
        return m, 200, None, info
    out = i_combine(m["per_role"])
    info["combine"] = out
    info["pair"] = copy.deepcopy(m["per_role"])
    if out["verdict"] is None:
        m_failed(m, out["reason"], out["by"], now)
    else:
        m_finalize(m, out["verdict"], out["reason"], out["flight"], "verdict", None, now)
    return m, 200, None, info


def m_fail(m, op, r, now, info):
    at, reason = op["attempt"], op["reason"]
    if reason not in PHONE:
        return m, 400, "bad_reason", info
    if not int_strict(at):
        return m, 400, "bad_attempt", info
    if m["state"] in ("confirmed", "started") and at < m["attempt"]:
        info["stale"] = True
        return m, 409, "stale_attempt", info
    if m["state"] not in ("confirmed", "started"):
        return m, 409, "bad_state", info
    if at != m["attempt"]:
        return m, 400, "bad_attempt", info
    if m["submitted"][r]:
        return m, 409, "already_submitted", info
    m["per_role"][r]["fail"] = reason
    m_failed(m, reason, r, now)
    return m, 200, None, info


# ---------------------------------------------------------------- the real document, abstracted the same way

def abstract(ctx, d):
    if d is None:
        return None
    base = ctx.base

    def rel(x):
        return None if x is None else x - base

    def stored_rec(p):
        """The commit's rec field, stored under the key for the armed version and no other."""
        key, other = ("rec_root", "rec_sha256") if p.get("popt") == 2 else ("rec_sha256", "rec_root")
        return "?" if other in p or key not in p else int(p[key], 16)

    def pr(p, role, attempt):
        out = {}
        if "sample_rate" in p:
            out.update(sr=p["sample_rate"], popt=p.get("popt"), cal=p.get("cal_us"))
        if "commit_b64" in p:
            out.update(cm=ctx.cm_label.get(p["commit_b64"], "?"), cms=ctx.sig_label.get(p["commit_sig_b64"], "?"),
                       cmh=ctx.cm_hash.get(p.get("commit_sha256"), "?"), rec=stored_rec(p))
        if "code_commit" in p:
            out["cc"] = True if p["code_commit"] == ctx.want_code_commit(role, attempt, p.get("sample_rate")) else "?"
        if "transcript_b64" in p:
            out.update(tx=ctx.tx_label.get(p["transcript_b64"], "?"), txs=ctx.sig_label.get(p["sig_b64"], "?"),
                       txh=ctx.tx_hash.get(p.get("transcript_sha256"), "?"), half=p["half"], delta=p["self_os_delta"])
        if "fail" in p:
            out["fail"] = p["fail"]["reason"]
        return out

    def row(a):
        out = {k: a[k] for k in ("attempt", "outcome", "reason", "by")}
        if "per_role" in a:
            out["per_role"] = {r: pr(a["per_role"][r], r, a["attempt"]) for r in ROLES}
            out["t0"] = rel(a["t0_ms"])
        if "verdict" in a:
            out.update(verdict=a["verdict"], flight=a["flight_cm"])
        return out

    res = None if d["result"] is None else abstract_result(ctx, d["result"])
    lf = d.get("last_failure")
    return {"state": d["state"], "attempt": d["attempt"], "seq": d["seq"], "guest": ctx.phone_name(d["guest_device_id"]),
            "confirmed": d["confirmed"], "armed": d["armed"], "committed": d["committed"], "submitted": d["submitted"], "t0": rel(d["t0_ms"]),
            "token_exp": rel(d["token_expires_ms"]), "finished": rel(d["finished_ms"]), "error": d["error"],
            "last_failure": None if lf is None else {k: lf[k] for k in ("attempt", "reason", "by")},
            "per_role": {r: pr(d["per_role"][r], r, d["attempt"]) for r in ROLES}, "attempts": [row(a) for a in d["attempts"]], "result": res}


def abstract_result(ctx, x):
    t0 = x["t0_ms"]
    return {"verdict": x["verdict"], "reason": x["reason"], "flight": x["flight_cm"], "attempt": x["attempt"], "t0": None if t0 is None else t0 - ctx.base,
            "devices": {r: {"half": v["half"], "sr": v["sample_rate"], "popt": v["popt"], "cal": v["cal_us"]} for r, v in x["devices"].items()},
            "tx": {r: ctx.tx_label.get(v["transcript_b64"], "?") for r, v in x["transcripts"].items()},
            "txs": {r: ctx.sig_label.get(v["sig_b64"], "?") for r, v in x["transcripts"].items()},
            "txh": {r: ctx.tx_hash.get(v["sha256"], "?") for r, v in x["transcripts"].items()},
            "cm": {r: ctx.cm_label.get(v["commit_b64"], "?") for r, v in x["commits"].items()},
            "cms": {r: ctx.sig_label.get(v["sig_b64"], "?") for r, v in x["commits"].items()},
            "rows": [{k: v for k, v in dict(a, flight=a.get("flight_cm")).items() if k != "flight_cm" and (k != "flight" or "verdict" in a)}
                     for a in x["attempts"]]}


def same(a, b):
    """A label for a value that must stay secret or random: equal to what it should be, or not."""
    return "ok" if a == b else "?"


def iso_rel(ctx, text):
    """created_at and finished_at, as ms since created_ms. They have millisecond text, so nothing is lost."""
    if text is None:
        return None
    return round(datetime.fromisoformat(text).timestamp() * 1000) - ctx.base


def full_record(ctx, x):
    """RECORD in the trace format: every field the Lean Record has. Read from the record itself."""
    keys = {p.pub.hex(): n for n, p in ctx.phones.items()}
    out = abstract_result(ctx, x)
    out.update(sid=same(x["session_id"], ctx.sid), nonce=same(x["session_nonce"], ctx.doc_nonce_hex),
               created=iso_rel(ctx, x["created_at"]), finished=iso_rel(ctx, x["finished_at"]))
    for r, v in x["devices"].items():
        out["devices"][r].update(dev=ctx.names.get(v["device_id"], "?"), pk=keys.get(v["pubkey"], "?"))
    return out


def trace_extra(ctx, d):
    """EXTRA in the trace format: more fields of the stored document that the Lean Doc also has."""
    def times(p):
        out = {}
        if "armed_ms" in p:
            out["armed"] = p["armed_ms"] - ctx.base
        if "committed_ms" in p:
            out["committed"] = p["committed_ms"] - ctx.base
        if "fail" in p:
            out["fail_ms"] = p["fail"]["ms"] - ctx.base
        return out
    return {"sid": same(d["session_id"], ctx.sid), "seed": same(d["seed_hex"], ctx.seed), "nonce": same(d["nonce_hex"], ctx.doc_nonce_hex),
            "token": same(d["join_token"], ctx.token), "host": ctx.phone_name(d["host_device_id"]), "created": d["created_ms"] - ctx.base,
            "per_role": {r: times(d["per_role"][r]) for r in ROLES},
            "rows": [{"per_role": {r: times(a["per_role"][r]) for r in ROLES}} if "per_role" in a else {} for a in d["attempts"]],
            "result": None if d["result"] is None else full_record(ctx, d["result"])}


