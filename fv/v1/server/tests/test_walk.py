def direct_numbers(rng, n, counts):
    """V1 to V5 on random inputs, away from any session. Raises AssertionError with the input."""
    # V2, on rationals, close to both ends and far away
    for _ in range(n):
        f = rng.choice([Fraction(rng.randint(-10 ** 6, 10 ** 6), rng.randint(1, 10 ** 4)), Fraction(-20) + Fraction(rng.randint(-3, 3), rng.randint(1, 10 ** 6)),
                        Fraction(60) + Fraction(rng.randint(-3, 3), rng.randint(1, 10 ** 6)), Fraction(-20), Fraction(60)])
        want = (None, "impossible_flight") if f <= -20 else (("NOT_NEAR", "too_far") if f >= 60 else ("NEAR", None))
        assert V.decide(f) == want, f"V2 at {f}"
        counts["V2 decide"] += 1
    # V3, with exact ties at multiples of 1715
    for _ in range(n):
        if rng.random() < 0.3:
            k = rng.randint(21, 55)
            sa, sb = 1715 * k, 1715 * rng.randint(21, 55)
            ha, hb = rng.choice([6, -2]) * k + rng.choice([0, 0, 1, -1]), 0
        else:
            sa, sb = rng.randint(SR_MIN, SR_MAX), rng.randint(SR_MIN, SR_MAX)
            hb = rng.randint(-2 ** 31, 2 ** 31 - 1)
            ha = int((rng.uniform(-30, 70) / 17150 + hb / sb) * sa) if rng.random() < 0.7 else rng.randint(-2 ** 31, 2 ** 31 - 1)
            ha = max(-2 ** 31, min(2 ** 31 - 1, ha))
        f = V.flight_exact(ha, sa, hb, sb)
        n_, s_ = ha * sb - hb * sa, sa * sb
        assert (Fraction(-20) < f < 60) == (-40 * s_ < 34300 * n_ < 120 * s_), f"V3 at {ha},{sa},{hb},{sb}"
        assert f == i_flight(ha, sa, hb, sb), "flight_exact"
        counts["V3 integer form"] += 1
    # V4, with both edges
    for _ in range(n):
        sr = rng.randint(SR_MIN, SR_MAX)
        cal = rng.choice([0, 0, rng.randint(0, 50000), rng.randint(-2000, 2000)])
        top = (cal * sr + 50000 * sr) // 1_000_000
        low = -((-(cal * sr) + 50000 * sr) // 1_000_000)
        d = rng.choice([top, top + 1, low, low - 1, rng.randint(-200000, 200000)])
        assert V.self_os_ok(d, sr, cal) == (abs(d * 10 ** 6 - cal * sr) <= 50 * 1000 * sr), f"V4 at {d},{sr},{cal}"
        counts["V4 self check"] += 1
    assert V.self_os_ok(2400, 48000) and V.self_os_ok(-2400, 48000) and not V.self_os_ok(2401, 48000) and not V.self_os_ok(-2401, 48000)
    assert V.self_os_ok(480 + 2400, 48000, 10000) and not V.self_os_ok(480 + 2401, 48000, 10000)
    # V1 and V5 on direct combine calls, with random field changes
    sk = {r: ec.generate_private_key(ec.SECP256R1()) for r in ROLES}
    pk = {r: pub_bytes(sk[r].public_key()) for r in ROLES}
    outsider = b"\x04" + b"\x33" * 64
    for _ in range(n):
        sa, sb = rng.randint(SR_MIN, SR_MAX), rng.randint(SR_MIN, SR_MAX)
        hb = rng.choice([rng.randint(-5000, 5000), rng.randint(-2 ** 31, 2 ** 31 - 1)])
        ha = max(-2 ** 31, min(2 ** 31 - 1, int((rng.uniform(-40, 80) / 17150 + hb / sb) * sa)))
        da, db = rng.choice([0, 100, 2400, 2401, -2401, rng.randint(-5000, 5000)]), rng.choice([0, 100, 2400, 2401, -2401, rng.randint(-5000, 5000)])
        ca, cb = rng.choice([0, 0, 10000]), rng.choice([0, 0, 10000])
        ta = {"role": "A", "nonce": b"n" * 32, "attempt": 0, "pk_self": pk["A"], "pk_partner": pk["B"], "sample_rate": sa, "half": ha, "self_os_delta": da}
        tb = {"role": "B", "nonce": b"n" * 32, "attempt": 0, "pk_self": pk["B"], "pk_partner": pk["A"], "sample_rate": sb, "half": hb, "self_os_delta": db}
        va, vb = rng.choice([1, 1, 2]), rng.choice([1, 1, 2])   # a v2 transcript's delta is already calibrated, so cal is not used
        ta["version"], tb["version"] = va, vb
        how = rng.choice(["pair", "pair", "pair", "pair", "role_a", "role_b", "nonce", "attempt", "partner_a", "partner_b", "same_key", "swap"])
        x, y = dict(ta), dict(tb)
        if how == "role_a":   # each of these breaks one clause of "pair", and only that one
            x["role"] = "B"
        elif how == "role_b":
            y["role"] = "A"
        elif how == "nonce":
            y["nonce"] = b"m" * 32
        elif how == "attempt":
            y["attempt"] = 1
        elif how == "partner_a":
            x["pk_partner"] = outsider
        elif how == "partner_b":
            y["pk_partner"] = outsider
        elif how == "same_key":
            x["pk_self"], y["pk_self"], x["pk_partner"], y["pk_partner"] = pk["A"], pk["A"], pk["A"], pk["A"]
        elif how == "swap":
            x, y = y, x
        cal = {"A": ca, "B": cb}
        try:
            out = V.combine(x, y, cal)
        except V.Reject as e:
            assert how != "pair", f"V1: a good pair raised {e.reason}"
            assert e.reason == "transcript_mismatch", f"V1: {e.reason}"
            counts["V1 not a pair: rejected"] += 1
            if how == "swap":
                counts["V5 combine swapped"] += 1
            else:
                counts[f"V1 clause broken alone: {how}"] += 1
            continue
        assert how == "pair", f"V1: {how} passed combine"
        ok_a, ok_b = i_self_ok(da, sa, 0 if va == 2 else ca), i_self_ok(db, sb, 0 if vb == 2 else cb)
        if not ok_a:
            assert (out["verdict"], out["reason"], out["by"]) == (None, "self_timestamp_mismatch", "A"), "V1: A's self check first"
        elif not ok_b:
            assert (out["verdict"], out["reason"], out["by"]) == (None, "self_timestamp_mismatch", "B"), "V1: then B's"
        else:
            v = i_verdict(ha, sa, hb, sb)
            assert out["verdict"] == {"near": "NEAR", "far": "NOT_NEAR", "impossible": None}[v], f"V1: {ha},{sa},{hb},{sb}"
            assert out["flight_cm"] == round(float(i_flight(ha, sa, hb, sb)), 2), "V1: shown flight"
        counts[f"V1 pair: {out['reason'] or 'near'}"] += 1


def direct_records(rng, n, counts):
    """V7 and V5 on records built here, with no session: real keys, real signatures, random numbers. The keys named in the mapping table only."""
    for _ in range(n):
        sk = {r: ec.generate_private_key(ec.SECP256R1()) for r in ROLES}
        pk = {r: pub_bytes(sk[r].public_key()) for r in ROLES}
        nonce, attempt = bytes(rng.randrange(256) for _ in range(32)), rng.choice([0, 1])
        sr = {r: rng.randint(SR_MIN, SR_MAX) for r in ROLES}
        ver = {r: rng.choice([1, 1, 2]) for r in ROLES}
        cal = {r: rng.choice([0, 0, 3000, 10000]) for r in ROLES}
        hb = rng.randint(-5000, 5000)
        ha = int((rng.uniform(-40, 80) / 17150 + hb / sr["B"]) * sr["A"])
        half = {"A": ha, "B": hb}
        delta = {r: rng.choice([int(round((0 if ver[r] == 2 else cal[r]) * sr[r] / 1e6)), rng.randint(-5000, 5000)]) for r in ROLES}
        rec = {"session_nonce": nonce.hex(), "attempt": attempt, "verdict": "NOT_NEAR", "reason": "x", "flight_cm": None, "devices": {}, "transcripts": {}, "commits": {}}
        for r in ROLES:
            rv = rng.randint(1, 2 ** 64).to_bytes(32, "big")
            craw = encode_commit(r, attempt, nonce, rv, ver[r])
            t = {"role": r, "attempt": attempt, "nonce": nonce, "pk_self": pk[r], "pk_partner": pk[OTHER[r]], "sample_rate": sr[r], "half": half[r],
                 ("rec_root" if ver[r] == 2 else "rec_sha256"): rv, "play_frame_position": 1, "play_nano_time": 2, "rec_frame0_nano_time": 3,
                 "self_os_delta": delta[r], "commit_hash": hashlib.sha256(craw).digest()}
            if ver[r] == 2:
                t.update(version=2, a_self=70000, p_partner=71000, delta=popt2.delta(sr[r]), code_commit=b"\x01" * 32)
            traw = encode_transcript(t)
            rec["devices"][r] = {"pubkey": pk[r].hex(), "cal_us": cal[r]}
            rec["commits"][r] = {"commit_b64": b64(craw), "sig_b64": b64(sign_raw(sk[r], craw))}
            rec["transcripts"][r] = {"transcript_b64": b64(traw), "sig_b64": b64(sign_raw(sk[r], traw))}
        how = rng.choice(["good", "good", "good", "good", "no_transcript", "no_commit", "bad_sig", "swap_tx", "swap_all", "attempt", "nonce", "shown_fields"])
        want_reason = "transcript_mismatch"
        if how == "no_transcript":
            del rec["transcripts"][rng.choice(ROLES)]
        elif how == "no_commit":
            del rec["commits"][rng.choice(ROLES)]
        elif how == "bad_sig":
            r = rng.choice(ROLES)
            part = rng.choice(["commits", "transcripts"])
            sig = base64.b64decode(rec[part][r]["sig_b64"])
            rec[part][r]["sig_b64"] = b64(sig[:-1] + bytes([sig[-1] ^ 1]))
            want_reason = "signature_invalid"
        elif how == "swap_tx":
            rec["transcripts"]["A"], rec["transcripts"]["B"] = rec["transcripts"]["B"], rec["transcripts"]["A"]
            want_reason = "signature_invalid"
        elif how == "swap_all":
            for part in ("transcripts", "commits", "devices"):
                rec[part]["A"], rec[part]["B"] = rec[part]["B"], rec[part]["A"]
        elif how == "attempt":
            rec["attempt"] = 1 - attempt
        elif how == "nonce":
            rec["session_nonce"] = (b"\xee" * 32).hex()
        elif how == "shown_fields":   # spec V7: verify_record never compares these, so changing them changes nothing
            rec.update(verdict="NEAR", reason=None, flight_cm=12.5)
            rec["devices"]["A"]["half"] = 123456
        try:
            out = V.verify_record(rec)
        except V.Reject as e:
            assert how not in ("good", "shown_fields"), f"V7: a good record raised {e.reason}"
            assert e.reason == want_reason, f"V7: {how} raised {e.reason}, wanted {want_reason}"
            counts[f"V7 refused: {how}"] += 1
            if how in ("swap_tx", "swap_all"):
                counts[f"V5 record: {how}"] += 1
            continue
        assert how in ("good", "shown_fields"), f"V7: {how} passed verify_record"
        p = {r: {"delta": delta[r], "sr": sr[r], "popt": ver[r], "cal": cal[r], "half": half[r]} for r in ROLES}
        want = i_combine(p)
        got = {"verdict": out["verdict"], "reason": out["reason"], "by": out["by"], "flight": out["flight_cm"]}
        assert got == want, f"V7: replay {got}, the rules say {want}"
        counts[f"V7 replay: {out['reason'] or 'near'}"] += 1


