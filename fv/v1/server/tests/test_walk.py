def neutralize(clause):
    """A combine with one clause of "pair" removed: the inputs are bent so that this clause always holds, and nothing else changes."""
    def weak(orig):
        def run(ta, tb, cal=None):
            ta, tb = dict(ta), dict(tb)
            if clause == "role_a":
                ta["role"] = "A"
            elif clause == "role_b":
                tb["role"] = "B"
            elif clause == "nonce":
                tb["nonce"] = ta["nonce"]
            elif clause == "attempt":
                tb["attempt"] = ta["attempt"]
            elif clause == "partner_a":
                ta["pk_partner"] = tb["pk_self"]
            elif clause == "partner_b":
                tb["pk_partner"] = ta["pk_self"]
            elif clause == "same_key" and ta["pk_self"] == tb["pk_self"]:
                ta["pk_self"] = b"\x04" + b"\x44" * 64
                tb["pk_partner"] = ta["pk_self"]
            return orig(ta, tb, cal)
        return run
    return weak


@pytest.mark.parametrize("clause", ["role_a", "role_b", "nonce", "attempt", "partner_a", "partner_b", "same_key"])
def test_pair_clause_mutation(clause, monkeypatch):
    """Live traffic can't reach these, since check_transcript pins each field first. So direct inputs must catch each one alone."""
    monkeypatch.setattr(V, "combine", neutralize(clause)(V.combine))
    with pytest.raises(AssertionError, match=f"V1: {clause} passed combine"):
        direct_numbers(random.Random(11), 2000, Counter())


