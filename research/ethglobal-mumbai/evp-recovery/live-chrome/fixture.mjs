// Build verify/test/LiveFixture.sol from Chrome-minted tokens. No deps.
// node fixture.mjs tmp/keys/issuer.jwk.json token-chrome-1.txt tokens/*.txt
import { readFileSync, writeFileSync } from "node:fs";
const [jwkPath, ...files] = process.argv.slice(2);
const jwk = JSON.parse(readFileSync(jwkPath, "utf8"));
const ctx = JSON.parse(readFileSync(new URL("../ctx-vector.json", import.meta.url), "utf8"));
const EMAIL = "alice@tawago.test", AUD = "https://recover.tawago.test";
const hx = (b64) => "0x" + Buffer.from(b64, "base64url").toString("hex");
// Same as poc-evp-issuer/mint.mjs offsets(): indexOf, so claim order does not matter.
function offsets(token) {
  const d1 = token.indexOf("."), d2 = token.indexOf(".", d1 + 1), t = token.indexOf("~");
  const k1 = token.indexOf(".", t + 1), k2 = token.indexOf(".", k1 + 1);
  const ep = Buffer.from(token.slice(d1 + 1, d2), "base64url").toString("utf8");
  const kp = Buffer.from(token.slice(k1 + 1, k2), "base64url").toString("utf8");
  const at = (s, n) => { const i = s.indexOf(n); if (i < 0) throw new Error(n); return i; };
  const f = [d1, d2, t, k1, k2, at(ep, '"email":"'), Buffer.byteLength(EMAIL), at(ep, '"email_verified":true'), at(ep, '"iat":'),
    at(ep, '"x":"'), at(ep, '"y":"'), at(kp, '"aud":"'), at(kp, '"nonce":"'), at(kp, '"iat":'), at(kp, '"sd_hash":"')];
  return "0x" + f.reduce((a, v, i) => a | (BigInt(v) << BigInt(16 * i)), 0n).toString(16);
}
const toks = files.map((f) => readFileSync(f, "utf8").trim());
const iat = (t) => JSON.parse(Buffer.from(t.split("~")[1].split(".")[1], "base64url").toString()).iat;
const sol = `// SPDX-License-Identifier: MIT
// GENERATED by live-chrome/fixture.mjs at ${new Date().toISOString()}. Tokens minted by real Chrome 156. Test keys only.
pragma solidity ^0.8.24;

library LiveFixture {
    uint256 constant ISSUER_X = ${hx(jwk.x)};
    uint256 constant ISSUER_Y = ${hx(jwk.y)};
    bytes constant EVT_HEADER_B64 = "${toks[0].split(".")[0]}";
    bytes constant EMAIL = "${EMAIL}";
    bytes constant AUD = "${AUD}";
    // nonce = keccak(preimage) = ctx, so the unchanged verifier takes preimage as its newKey arg.
    bytes constant PREIMAGE = hex"${ctx.preimage.slice(2)}";
    uint256 constant N = ${toks.length};
    function tok(uint256 i) internal pure returns (bytes memory t, uint256 offs, uint256 iat) {
${toks.map((t, i) => `        if (i == ${i}) return ("${t}", ${offsets(t)}, ${iat(t)});`).join("\n")}
        revert("idx");
    }
}
`;
writeFileSync(new URL("verify/test/LiveFixture.sol", import.meta.url), sol);
console.log("tokens:", toks.length);
