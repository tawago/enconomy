// Copied from ../../poc-evp-issuer/mint.mjs (2026-11-03); writes only under this dir.
// Mint a sample EVP token (EVT~KB-JWT) with fresh P-256 test keys, then
// write test/Fixture.sol for the forge verifier.
// No npm deps. keccak256 comes from `cast keccak` (foundry).
// Usage: node mint.mjs [email] [aud]
import { generateKeyPairSync, createHash, sign } from "node:crypto";
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const EMAIL = process.argv[2] ?? "alice@pop.enconomy.dev";
const AUD = process.argv[3] ?? "https://webapp.enconomy.dev";
const ISS = "https://issuer.enconomy.dev";

const b64u = (buf) => Buffer.from(buf).toString("base64url");
const jwtPart = (obj) => b64u(Buffer.from(JSON.stringify(obj), "utf8"));
const keccak = (hex) => execFileSync("cast", ["keccak", hex]).toString().trim();

function newP256() {
  const { privateKey, publicKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = publicKey.export({ format: "jwk" });
  return { privateKey, jwk };
}
// ES256 = ECDSA P-256 over SHA-256, signature is raw r||s (64 bytes), not DER.
const es256 = (key, input) => sign("sha256", Buffer.from(input, "ascii"), { key, dsaEncoding: "ieee-p1363" });
const hex = (b) => "0x" + Buffer.from(b).toString("hex");
const jwkXY = (jwk) => [hex(Buffer.from(jwk.x, "base64url")), hex(Buffer.from(jwk.y, "base64url"))];

mkdirSync(join(here, "keys"), { recursive: true });
const issuer = newP256();   // issuer signing key (JWKS entry)
const browser = newP256();  // Chrome's per-request key (cnf.jwk)
const attacker = newP256(); // for a negative fixture: KB signed by a key not in cnf
const owner = newP256();    // the new account key being installed by recovery
for (const [n, k] of Object.entries({ issuer, browser, attacker, owner }))
  writeFileSync(join(here, "keys", `${n}.pem`), k.privateKey.export({ format: "pem", type: "pkcs8" }));

// newKey = uncompressed-less P-256 pubkey x||y (64 bytes). nonce = 0x + keccak256(newKey), lowercase hex.
const [ox, oy] = jwkXY(owner.jwk);
const newKey = ox + oy.slice(2);
const nonce = keccak(newKey);

const iat = Math.floor(Date.now() / 1000);

// EVT (issuer-signed). Claims per draft-hardt-email-verification-02 s5.1.
const evtHeader = { alg: "ES256", typ: "evt+jwt", kid: "pop-1" };
const evtPayload = {
  iss: ISS,
  iat,
  cnf: { jwk: { kty: "EC", crv: "P-256", x: browser.jwk.x, y: browser.jwk.y } },
  email: EMAIL,
  email_verified: true,
};
const evtInput = jwtPart(evtHeader) + "." + jwtPart(evtPayload);
const evt = evtInput + "." + b64u(es256(issuer.privateKey, evtInput));
const issuanceToken = evt + "~"; // SD-JWT with zero disclosures, trailing tilde

// KB-JWT (browser-signed). sd_hash = b64url(SHA-256(issuance token incl. "~")).
function kb(key, it = issuanceToken) {
  const h = { alg: "ES256", typ: "kb+jwt" };
  const p = { aud: AUD, nonce, iat, sd_hash: b64u(createHash("sha256").update(it, "ascii").digest()) };
  const input = jwtPart(h) + "." + jwtPart(p);
  return { p, jwt: input + "." + b64u(es256(key, input)) };
}

function offsets(token) {
  const d1 = token.indexOf(".");
  const d2 = token.indexOf(".", d1 + 1);
  const t = token.indexOf("~");
  const k1 = token.indexOf(".", t + 1);
  const k2 = token.indexOf(".", k1 + 1);
  const ep = Buffer.from(token.slice(d1 + 1, d2), "base64url").toString("utf8");
  const kp = Buffer.from(token.slice(k1 + 1, k2), "base64url").toString("utf8");
  const at = (s, needle) => { const i = s.indexOf(needle); if (i < 0) throw new Error(needle); return i; };
  const f = [
    d1, d2, t, k1, k2,
    at(ep, '"email":"'), Buffer.byteLength(EMAIL), at(ep, '"email_verified":true'), at(ep, '"iat":'),
    at(ep, '"x":"'), at(ep, '"y":"'),
    at(kp, '"aud":"'), at(kp, '"nonce":"'), at(kp, '"iat":'), at(kp, '"sd_hash":"'),
  ];
  f.forEach((v) => { if (v < 0 || v > 0xffff) throw new Error("offset range"); });
  return "0x" + f.reduce((acc, v, i) => acc | (BigInt(v) << BigInt(16 * i)), 0n).toString(16);
}

const good = issuanceToken + kb(browser.privateKey).jwt;
const bad = issuanceToken + kb(attacker.privateKey).jwt; // KB key != cnf.jwk
// Same claims, fresh issuer signature (ECDSA is randomized), so a different EVT string.
// KB-JWT made for the first EVT: sd_hash must not match.
const evt2 = evtInput + "." + b64u(es256(issuer.privateKey, evtInput)) + "~";
const swapped = evt2 + kb(browser.privateKey).jwt;
const [ix, iy] = jwkXY(issuer.jwk);
const evtHeaderB64 = jwtPart(evtHeader);

const sol = `// SPDX-License-Identifier: MIT
// GENERATED by mint.mjs at ${new Date().toISOString()}. Test keys only.
pragma solidity ^0.8.24;

library Fixture {
    bytes constant TOKEN = "${good}";
    uint256 constant OFFS = ${offsets(good)};
    bytes constant TOKEN_WRONG_KB_KEY = "${bad}";
    uint256 constant OFFS_WRONG_KB_KEY = ${offsets(bad)};
    bytes constant TOKEN_SD_SWAP = "${swapped}";
    uint256 constant OFFS_SD_SWAP = ${offsets(swapped)};
    uint256 constant ISSUER_X = ${ix};
    uint256 constant ISSUER_Y = ${iy};
    bytes constant EVT_HEADER_B64 = "${evtHeaderB64}";
    bytes constant EMAIL = "${EMAIL}";
    bytes constant AUD = "${AUD}";
    bytes constant NEW_KEY = hex"${newKey.slice(2)}";
    uint256 constant IAT = ${iat};
}
`;
writeFileSync(join(here, "test", "Fixture.sol"), sol);
writeFileSync(join(here, "sample-token.txt"), good + "\n");
console.log(JSON.stringify({ evtHeader, evtPayload, kbPayload: kb(browser.privateKey).p, tokenBytes: good.length, nonce }, null, 2));

// poc-native-evp addition: metadata for entries.cjs (TEST keys only, never funded).
const [bx, by] = jwkXY(browser.jwk);
const ownerD = hex(Buffer.from(owner.privateKey.export({ format: "jwk" }).d, "base64url"));
writeFileSync(join(here, "keys", "meta.json"), JSON.stringify({
  token: good, issuerX: ix, issuerY: iy, browserX: bx, browserY: by,
  ownerX: ox, ownerY: oy, ownerD, newKey, nonce, email: EMAIL, aud: AUD, iat,
}, null, 2));
