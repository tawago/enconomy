"""Writes src/Groth16N<n>.sol: a snarkjs-shaped BN254 Groth16 verifier with constant VK,
plus test/Groth16Fixtures.sol with one valid (proof, inputs) pair per n.

No circuit. The VK and proof are a synthetic but *valid* instance of the Groth16 pairing equation
  e(A,B) = e(alpha,beta) * e(vk_x,gamma) * e(C,delta),   vk_x = IC0 + sum x_i * IC_i
with beta = gamma = delta = B = G2 generator and every G1 point a known multiple of G1.
The precompiles price by input length/pair count only, so the gas equals a real proof's.
Scalars are fixed (deterministic), not secrets."""
import os, sys
P = 21888242871839275222246405745257275088696311157297823662689037894645226208583
R = 21888242871839275222246405745257275088548364400416034343698204186575808495617

def add(a, b):
    if a is None: return b
    if b is None: return a
    if a[0] == b[0] and (a[1] + b[1]) % P == 0: return None
    if a == b: l = 3 * a[0] * a[0] * pow(2 * a[1], -1, P) % P
    else: l = (b[1] - a[1]) * pow(b[0] - a[0], -1, P) % P
    x = (l * l - a[0] - b[0]) % P
    return (x, (l * (a[0] - x) - a[1]) % P)

def mul(k, pt=(1, 2)):
    out = None
    k %= R
    while k:
        if k & 1: out = add(out, pt)
        pt = add(pt, pt); k >>= 1
    return out

# G2 generator, EIP-197 order (x_im, x_re, y_im, y_re)
G2 = (11559732032986387107991004021392285783925812861821192530917403151452391805634,
      10857046999023057135944570762232829481370756359578518086990519993285655852781,
      4082367875863433681332203403145435568316851327593401208105741076214120093531,
      8495653923123431417604973247489272438418190587263600148770280649306958101930)

def verifier(n, alpha, ic):
    lines = [f"uint256 constant IC{i}x = {p[0]};\nuint256 constant IC{i}y = {p[1]};" for i, p in enumerate(ic)]
    msm = "\n".join(f"            g1_mulAccC(pVk, IC{i+1}x, IC{i+1}y, calldataload(add(pubSignals, {32*i})))" for i in range(n))
    chk = "\n".join(f"            checkField(calldataload(add(pubSignals, {32*i})))" for i in range(n))
    return f"""// SPDX-License-Identifier: MIT
// GENERATED by gen/gen_groth16.py. snarkjs-template-shaped Groth16 BN254 verifier, {n} public input(s).
pragma solidity ^0.8.28;

uint256 constant r = {R};
uint256 constant q = {P};
uint256 constant alphax = {alpha[0]};
uint256 constant alphay = {alpha[1]};
uint256 constant g2xi = {G2[0]};
uint256 constant g2xr = {G2[1]};
uint256 constant g2yi = {G2[2]};
uint256 constant g2yr = {G2[3]};
{chr(10).join(lines)}

contract Groth16N{n} {{
    function verifyProof(uint256[2] calldata pA, uint256[2][2] calldata pB, uint256[2] calldata pC,
                         uint256[{n}] calldata pubSignals) external view returns (bool) {{
        assembly {{
            function checkField(v) {{
                if iszero(lt(v, r)) {{ mstore(0, 0) return(0, 0x20) }}
            }}
            function g1_mulAccC(pR, x, y, s) {{
                let ok
                let mIn := mload(0x40)
                mstore(mIn, x)
                mstore(add(mIn, 32), y)
                mstore(add(mIn, 64), s)
                ok := staticcall(gas(), 7, mIn, 96, mIn, 64)
                if iszero(ok) {{ mstore(0, 0) return(0, 0x20) }}
                mstore(add(mIn, 64), mload(pR))
                mstore(add(mIn, 96), mload(add(pR, 32)))
                ok := staticcall(gas(), 6, mIn, 128, pR, 64)
                if iszero(ok) {{ mstore(0, 0) return(0, 0x20) }}
            }}
            let pMem := mload(0x40)
            mstore(0x40, add(pMem, 1600))
            let pVk := pMem
{chk}
            mstore(pVk, IC0x)
            mstore(add(pVk, 32), IC0y)
{msm}
            let p := add(pMem, 64)
            // -A, B
            mstore(p, calldataload(pA))
            mstore(add(p, 32), mod(sub(q, calldataload(add(pA, 32))), q))
            mstore(add(p, 64), calldataload(pB))
            mstore(add(p, 96), calldataload(add(pB, 32)))
            mstore(add(p, 128), calldataload(add(pB, 64)))
            mstore(add(p, 160), calldataload(add(pB, 96)))
            // alpha, beta
            mstore(add(p, 192), alphax)
            mstore(add(p, 224), alphay)
            mstore(add(p, 256), g2xi)
            mstore(add(p, 288), g2xr)
            mstore(add(p, 320), g2yi)
            mstore(add(p, 352), g2yr)
            // vk_x, gamma
            mstore(add(p, 384), mload(pVk))
            mstore(add(p, 416), mload(add(pVk, 32)))
            mstore(add(p, 448), g2xi)
            mstore(add(p, 480), g2xr)
            mstore(add(p, 512), g2yi)
            mstore(add(p, 544), g2yr)
            // C, delta
            mstore(add(p, 576), calldataload(pC))
            mstore(add(p, 608), calldataload(add(pC, 32)))
            mstore(add(p, 640), g2xi)
            mstore(add(p, 672), g2xr)
            mstore(add(p, 704), g2yi)
            mstore(add(p, 736), g2yr)
            let ok := staticcall(gas(), 8, p, 768, p, 0x20)
            mstore(0, and(ok, mload(p)))
            return(0, 0x20)
        }}
    }}
}}
"""

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
NS = [int(a) for a in sys.argv[1:]] or [1, 2, 4, 8, 16, 32]
fx = ["// SPDX-License-Identifier: MIT\n// GENERATED by gen/gen_groth16.py\npragma solidity ^0.8.28;\n\nlibrary Fx {"]
for n in NS:
    a_s, c_s = 1000 + n, 7777 + n
    ic_s = [31 * (i + 1) + n for i in range(n + 1)]
    xs = [(0xC0FFEE * (i + 3) + n) % R for i in range(n)]   # public inputs: full-width-ish field elements
    xs = [(x * 0x1234567890ABCDEF1234567890ABCDEF1234567890ABCDEF) % R for x in xs]
    vkx_s = (ic_s[0] + sum(x * s for x, s in zip(xs, ic_s[1:]))) % R
    A = mul(a_s + vkx_s + c_s)  # e(A,G2) = e(alpha,G2) e(vk_x,G2) e(C,G2)
    C = mul(c_s)
    with open(os.path.join(root, "src", f"Groth16N{n}.sol"), "w") as f:
        f.write(verifier(n, mul(a_s), [mul(s) for s in ic_s]))
    fx.append(f"    function n{n}() internal pure returns (uint256[2] memory a, uint256[2] memory c, uint256[{n}] memory x) {{")
    fx.append(f"        a = [uint256({A[0]}), {A[1]}];\n        c = [uint256({C[0]}), {C[1]}];")
    fx.append("".join(f"        x[{i}] = {v};\n" for i, v in enumerate(xs)) + "    }")
fx.append("    function b() internal pure returns (uint256[2][2] memory bb) {")
fx.append(f"        bb = [[uint256({G2[0]}), {G2[1]}], [uint256({G2[2]}), {G2[3]}]];\n    }}\n}}\n")
with open(os.path.join(root, "test", "Groth16Fixtures.sol"), "w") as f:
    f.write("\n".join(fx))
print("wrote", NS)
