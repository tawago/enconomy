"""Presence key, canonical bytes, device statement."""
import base64
import os
import stat

import pytest
from cryptography.hazmat.primitives.asymmetric import ec

from pop import presence
from pop.crypto import device_id, pub_bytes, sign_raw, verify_raw
from tests.phones import Phone, make_chain


def _pub(client):
    return bytes.fromhex(client.get("/v1/config").json()["presence"]["pubkey"])


def _ok(client, signed):
    return presence.verify(_pub(client), presence.TAG_STATEMENT, signed)


# -- canonical bytes

def test_canonical_bytes():
    got = presence.canonical({"b": [1, True, None], "a": {"é": "x", "c": "y"}})
    assert got == b'{"a":{"c":"y","\\u00e9":"x"},"b":[1,true,null]}'


@pytest.mark.parametrize("bad", [1.5, float("nan"), float("inf"), 0.0, [1.0], {"x": {"y": [2.0]}}, (1, 2), b"x", {1: "x"}])
def test_canonical_refuses(bad):
    with pytest.raises(ValueError):
        presence.canonical({"v": bad})


# -- signing

def test_sign_verify():
    sk = ec.generate_private_key(ec.SECP256R1())
    pub = pub_bytes(sk.public_key())
    s = presence.sign(sk, presence.TAG_RECORD, {"a": 1})
    assert presence.verify(pub, presence.TAG_RECORD, s)
    assert verify_raw(pub, b'pop-presence-v1\n{"a":1}', base64.b64decode(s["sig_b64"]))
    assert not presence.verify(pub, presence.TAG_RECORD, {**s, "body": {"a": 2}})


def test_domain_tags_not_interchangeable():
    sk = ec.generate_private_key(ec.SECP256R1())
    pub = pub_bytes(sk.public_key())
    s = presence.sign(sk, presence.TAG_STATEMENT, {"a": 1})
    assert presence.verify(pub, presence.TAG_STATEMENT, s)
    assert not presence.verify(pub, presence.TAG_RECORD, s)
    assert not presence.verify(pub, presence.TAG_STATEMENT, presence.sign(sk, presence.TAG_RECORD, {"a": 1}))


@pytest.mark.parametrize("bad", [None, {}, {"body": {"a": 1}}, {"body": {"a": 1}, "sig_b64": "!!"},
                                 {"body": {"a": 1}, "sig_b64": base64.b64encode(bytes(64)).decode()},
                                 {"body": {"a": 1.5}, "sig_b64": base64.b64encode(bytes(64)).decode()}])
def test_verify_malformed_is_false(bad):
    pub = pub_bytes(ec.generate_private_key(ec.SECP256R1()).public_key())
    assert presence.verify(pub, presence.TAG_RECORD, bad) is False


# -- key

def test_key_autogenerated_0600_and_stable(make_client, tmp_path, caplog):
    c = make_client()
    path = tmp_path / "presence.pem"
    assert stat.S_IMODE(os.stat(path).st_mode) == 0o600
    pub = _pub(c)
    assert c.get("/v1/config").json()["presence"]["alg"] == "p256" and len(pub) == 65
    assert _pub(make_client()) == pub
    new = [r.getMessage() for r in caplog.records if "presence key" in r.getMessage()]
    assert len(new) == 1 and "Safes" not in new[0]


@pytest.mark.parametrize("other", ["attest.pem", "issuer.pem"])
def test_presence_key_refuses_other_keys(make_client, tmp_path, other):
    with pytest.raises(RuntimeError):
        make_client(presence_key_file=str(tmp_path / other))


# -- trust tier

@pytest.mark.parametrize("platform,level,attested,tier", [
    ("android", "tee", True, "tee"),
    ("android", "strongbox", True, "strongbox"),
    ("android", "software", True, "unattested"),
    ("android", "unknown", True, "unattested"),
    ("android", "tee", False, "unattested"),
    ("android", "strongbox", False, "unattested"),
    ("ios", "secure_enclave", True, "app_attest"),
    ("ios", "software", True, "app_attest"),
    ("ios", "secure_enclave", False, "unattested"),
    ("web", "software", False, "software"),
    ("other", "tee", True, "unattested"),
])
def test_trust_tier(platform, level, attested, tier):
    assert presence.trust_tier({"platform": platform, "security_level": level}, attested) == tier


# -- statement

def test_enroll_returns_statement(client, clock):
    p = Phone(client, clock)
    s = p.enroll().json()["device_statement"]
    assert s["body"] == {"format": "pop-device-statement-v1", "device_id": p.device_id, "pubkey": p.pub.hex(),
                         "attested": True, "platform": "android", "trust_tier": "tee", "issued_at_ms": clock()}
    assert _ok(client, s)
    assert s["body"]["device_id"] == device_id(bytes.fromhex(s["body"]["pubkey"]))


def test_enroll_strongbox_tier(client, clock):
    p = Phone(client, clock)
    n = client.get("/v1/enroll/nonce").json()["nonce"]
    r = client.post("/v1/enroll", json=p.enroll_body(n, make_chain(p.sk.public_key(), bytes.fromhex(n), level=2)))
    assert r.json()["device_statement"]["body"]["trust_tier"] == "strongbox"


def test_statement_unsigned_tampered_or_foreign_fails(client, clock):
    s = Phone(client, clock).enroll().json()["device_statement"]
    assert not _ok(client, {"body": s["body"]})
    assert not _ok(client, {**s, "body": {**s["body"], "attested": False}})
    assert not _ok(client, {**s, "body": {**s["body"], "trust_tier": "strongbox"}})
    foreign = ec.generate_private_key(ec.SECP256R1())
    assert not _ok(client, presence.sign(foreign, presence.TAG_STATEMENT, s["body"]))
    assert not presence.verify(pub_bytes(foreign.public_key()), presence.TAG_STATEMENT, s)


def test_statement_not_signed_by_the_attest_key(client, clock):
    from pop import attest
    s = Phone(client, clock).enroll().json()["device_statement"]
    att = attest.load_key(client.app.state.cfg.attest_key_file)
    assert not presence.verify(pub_bytes(att.public_key()), presence.TAG_STATEMENT, s)


def test_refetch(client, clock):
    p = Phone(client, clock)
    first = p.enroll().json()["device_statement"]
    clock.advance(60)
    r = p.get("/v1/device/statement")
    assert r.status_code == 200, r.text
    s = r.json()
    assert _ok(client, s) and s["body"]["issued_at_ms"] == clock() > first["body"]["issued_at_ms"]
    assert {**s["body"], "issued_at_ms": 0} == {**first["body"], "issued_at_ms": 0}


def test_refetch_requires_auth(client, clock):
    p = Phone(client, clock)
    assert p.get("/v1/device/statement").status_code == 401   # not enrolled yet
    p.enroll()
    assert client.get("/v1/device/statement").status_code == 401
    r = p.get("/v1/device/statement", sk=ec.generate_private_key(ec.SECP256R1()))
    assert r.status_code == 401 and r.json()["error"] == "auth_bad_signature"
    bad = client.get("/v1/device/statement?x=1", headers=p.headers("GET", "/v1/device/statement", b""))
    assert bad.status_code == 401


def test_unattested_statement_never_uses_reported_level(make_client, clock):
    c = make_client(allow_unattested=True)
    p = Phone(c, clock)
    s = p.enroll(attested=False).json()["device_statement"]
    assert s["body"]["attested"] is False and s["body"]["trust_tier"] == "unattested" and _ok(c, s)
    assert c.app.state.store.get_device(p.device_id)["security_level"] == "tee"   # what it reported
    assert p.get("/v1/device/statement").json()["body"]["trust_tier"] == "unattested"


def test_web_statement(make_client, clock):
    c = make_client(allow_web=True)
    p = Phone(c, clock)
    n = c.get("/v1/enroll/nonce").json()["nonce"]
    s = c.post("/v1/enroll", json={**p.enroll_body(n, None), "platform": "web"}).json()["device_statement"]
    assert s["body"]["attested"] is False and s["body"]["platform"] == "web"
    assert s["body"]["trust_tier"] == "software" and _ok(c, s)


def test_old_row_statement_not_attested(client, clock):
    """attested=1 from before the pin: enroll's flag doesn't carry over to the statement."""
    p = Phone(client, clock)
    p.enroll()
    store = client.app.state.store
    other = make_chain(p.sk.public_key(), b"\x00" * 32, root_sk=ec.generate_private_key(ec.SECP256R1()))
    pem = "".join("-----BEGIN CERTIFICATE-----\n" + c + "\n-----END CERTIFICATE-----\n" for c in other)
    store.put_device({**store.get_device(p.device_id), "chain_pem": pem})
    body = p.get("/v1/device/statement").json()["body"]
    assert store.get_device(p.device_id)["attested"] is True
    assert body["attested"] is False and body["trust_tier"] == "unattested"


def test_phone_cannot_sign_its_own_statement(client, clock):
    p = Phone(client, clock)
    s = p.enroll().json()["device_statement"]
    own = base64.b64encode(sign_raw(p.sk, presence.TAG_STATEMENT + presence.canonical(s["body"]))).decode()
    assert not _ok(client, {**s, "sig_b64": own})
