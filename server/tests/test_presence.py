def _pub(client):
    return bytes.fromhex(client.get("/v1/config").json()["presence"]["pubkey"])


def _ok(client, signed):
    return presence.verify(_pub(client), presence.TAG_STATEMENT, signed)


# -- canonical bytes

def test_canonical_bytes():
    got = presence.canonical({"b": [1, True, None], "a": {"é": "x", "c": "y"}})
    assert got == b'{"a":{"c":"y","\\u00e9":"x"},"b":[1,true,null]}'


@pytest.mark.parametrize("bad", [1.5, float("nan"), float("inf"), 0.0, [1.0], {"x": {"y": [2.0]}}, (1, 2), b"x", {1: "x"}])
def test_canonical_refuses(bad):
    with pytest.raises(ValueError):
        presence.canonical({"v": bad})


# -- signing

def test_sign_verify():
    sk = ec.generate_private_key(ec.SECP256R1())
    pub = pub_bytes(sk.public_key())
    s = presence.sign(sk, presence.TAG_RECORD, {"a": 1})
    assert presence.verify(pub, presence.TAG_RECORD, s)
    assert verify_raw(pub, b'pop-presence-v1\n{"a":1}', base64.b64decode(s["sig_b64"]))
    assert not presence.verify(pub, presence.TAG_RECORD, {**s, "body": {"a": 2}})


def test_domain_tags_not_interchangeable():
    sk = ec.generate_private_key(ec.SECP256R1())
    pub = pub_bytes(sk.public_key())
    s = presence.sign(sk, presence.TAG_STATEMENT, {"a": 1})
    assert presence.verify(pub, presence.TAG_STATEMENT, s)
    assert not presence.verify(pub, presence.TAG_RECORD, s)
    assert not presence.verify(pub, presence.TAG_STATEMENT, presence.sign(sk, presence.TAG_RECORD, {"a": 1}))


@pytest.mark.parametrize("bad", [None, {}, {"body": {"a": 1}}, {"body": {"a": 1}, "sig_b64": "!!"},
                                 {"body": {"a": 1}, "sig_b64": base64.b64encode(bytes(64)).decode()},
                                 {"body": {"a": 1.5}, "sig_b64": base64.b64encode(bytes(64)).decode()}])
def test_verify_malformed_is_false(bad):
    pub = pub_bytes(ec.generate_private_key(ec.SECP256R1()).public_key())
    assert presence.verify(pub, presence.TAG_RECORD, bad) is False


